    @Test
    fun buildsValidQuery() {
        val query = DirectDnsParser.buildQuery("_moonraker._tcp")
        assertTrue(query.size > 12)
        // Question count is 1
        assertEquals(1, ((query[4].toInt() and 0xff) shl 8) or (query[5].toInt() and 0xff))
        // Query ends with QTYPE 12 (PTR) and QCLASS 1 (IN)
        val end = query.size
        val qtype = ((query[end - 4].toInt() and 0xff) shl 8) or (query[end - 3].toInt() and 0xff)
        val qclass = ((query[end - 2].toInt() and 0xff) shl 8) or (query[end - 1].toInt() and 0xff)
        assertEquals(12, qtype)
        assertEquals(1, qclass)
    }

    @Test
    fun ignoresQueryPackets() {
        val query = DirectDnsParser.buildQuery("_moonraker._tcp")
        // QR bit is 0, so parse should return null
        assertNull(DirectDnsParser.parse(query, query.size))
    }
