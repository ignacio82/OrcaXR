async function readBody(request: IncomingMessage): Promise<Buffer> {
  const chunks: Buffer[] = [];
  for await (const chunk of request) chunks.push(chunk as Buffer);
  return Buffer.concat(chunks);
}

/** Minimal multipart reader: enough to prove the exact bytes crossed the wire. */
function parseSingleFileMultipart(body: Buffer, contentType: string): { filename: string; content: Buffer } {
  const boundary = /boundary=(?:"([^"]+)"|([^;]+))/i.exec(contentType);
  assert.ok(boundary, `expected a multipart boundary in ${contentType}`);
  const delimiter = `--${boundary[1] ?? boundary[2]}`;
  const parts = body.toString('binary').split(delimiter);
  for (const part of parts) {
    const headerEnd = part.indexOf('\r\n\r\n');
    if (headerEnd < 0) continue;
    const headers = part.slice(0, headerEnd);
    const filename = /filename="([^"]*)"/i.exec(headers)?.[1];
    if (!filename) continue;
    const content = part.slice(headerEnd + 4, part.lastIndexOf('\r\n'));
    return { filename, content: Buffer.from(content, 'binary') };
  }
  throw new Error('the upload carried no file part');
}
