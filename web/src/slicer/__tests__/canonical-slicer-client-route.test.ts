function requestFor(engine: SliceRouteRequest['engine']): SliceRouteRequest {
  return {
    protocolVersion: SLICE_PROTOCOL_VERSION,
    jobId: 'job-fixture',
    attempt: 1,
    plateId: 'plate-fixture' as PlateId,
    project: {
      bytes: encoder.encode('PK fixture canonical archive'),
      mediaType: 'model/3mf',
      inputHash: 'sha256:input',
      sourceRevision: 7,
      sourceHash: 'fnv1a64:source',
      sourceAssetHash: 'fnv1a64:assets',
    },
    profiles: { references: [], effectiveConfigHash: 'sha256:profiles' },
    engine,
    plateOverrides: {},
  };
}

function installExternalHarness(): {
  storage: MemoryStorage;
  requests: Request[];
  fetchImpl: (request: Request) => Promise<Response>;
  restore(): void;
} {
  const originalStorage = Object.getOwnPropertyDescriptor(globalThis, 'localStorage');
  const originalFetch = Object.getOwnPropertyDescriptor(globalThis, 'fetch');
  const storage = new MemoryStorage();
  const harness = {
    storage,
    requests: [] as Request[],
    fetchImpl: async (_request: Request): Promise<Response> => {
      throw new Error('fetchImpl not installed');
    },
    restore() {
      restoreProperty('localStorage', originalStorage);
      restoreProperty('fetch', originalFetch);
    },
  };
  Object.defineProperty(globalThis, 'localStorage', { configurable: true, value: storage });
  Object.defineProperty(globalThis, 'fetch', {
    configurable: true,
    value: (request: Request) => harness.fetchImpl(request),
  });
  return harness;
}

function installBrowserWorkerHarness(): {
  worker?: FakeWorker;
  restore(): void;
} {
  const descriptors = new Map(
    ['Worker', 'self', 'crossOriginIsolated'].map((name) => [name, Object.getOwnPropertyDescriptor(globalThis, name)]),
  );
  const harness: { worker?: FakeWorker; restore(): void } = {
    restore() {
      for (const [name, descriptor] of descriptors) restoreProperty(name, descriptor);
    },
  };
  Object.defineProperty(globalThis, 'crossOriginIsolated', { configurable: true, value: true });
  Object.defineProperty(globalThis, 'self', {
    configurable: true,
    value: { location: { origin: 'https://app.example.test' } },
  });
  Object.defineProperty(globalThis, 'Worker', {
    configurable: true,
    value: class {
      onmessage: ((event: MessageEvent) => void) | null = null;
      onerror: ((event: ErrorEvent) => void) | null = null;
      posted = false;
      terminated = false;
      constructor() {
        harness.worker = this;
      }
      postMessage(): void {
        this.posted = true;
      }
      terminate(): void {
        this.terminated = true;
      }
    } satisfies typeof FakeWorker,
  });
  return harness;
}

class FakeWorker {
  onmessage: ((event: MessageEvent) => void) | null = null;
  onerror: ((event: ErrorEvent) => void) | null = null;
  posted = false;
  terminated = false;
  postMessage(): void {}
  terminate(): void {}
}

function restoreProperty(name: string, descriptor: PropertyDescriptor | undefined): void {
  if (descriptor) Object.defineProperty(globalThis, name, descriptor);
  else Reflect.deleteProperty(globalThis, name);
}

function jsonResponse(body: unknown, status = 200): Response {
  return new Response(JSON.stringify(body), { status, headers: { 'Content-Type': 'application/json' } });
}

async function waitUntil(condition: () => boolean): Promise<void> {
  for (let attempt = 0; attempt < 100; attempt += 1) {
    if (condition()) return;
    await new Promise((resolve) => setTimeout(resolve, 0));
  }
  throw new Error('Timed out waiting for test condition');
}

