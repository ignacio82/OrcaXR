await test('adapter preserves abort reasons and never converts cancellation into a retryable route failure', async () => {
  const reason = new Error('cancelled by fixture');
  const client: CanonicalProjectSlicerClientPort = {
    sliceProjectWithRoute(_project, _route, options) {
      return new Promise((_resolve, reject) => {
        options?.signal?.addEventListener('abort', () => reject(options.signal!.reason), { once: true });
      });
    },
  };
  const adapter = new CanonicalSlicerClientRoute({ client, route: { kind: 'browser-wasm' } });
  const controller = new AbortController();
  const pending = adapter.execute(requestFor(adapter.metadata.engine), controller.signal);
  controller.abort(reason);
  await assert.rejects(
    pending,
    (error: unknown) =>
      error instanceof SliceRouteCancellationError &&
      error.cancellationConfirmed &&
      error.cancellationReason === reason,
  );
});

await test('adapter does not mask an unconfirmed underlying cancellation', async () => {
  const unconfirmed = new SlicerClientCancellationError('server cancellation could not be confirmed', false);
  const client: CanonicalProjectSlicerClientPort = {
    async sliceProjectWithRoute() {
      throw unconfirmed;
    },
  };
  const adapter = new CanonicalSlicerClientRoute({ client, route: { kind: 'browser-wasm' } });
  // Exercise the race after execution starts; a pre-aborted signal never calls the route.
  const active = new AbortController();
  const pending = adapter.execute(requestFor(adapter.metadata.engine), active.signal);
  active.abort(new Error('cancel requested'));
  await assert.rejects(
    pending,
    (error: unknown) =>
      error instanceof SliceRouteCancellationError && !error.cancellationConfirmed && error.cause === unconfirmed,
  );
});

await test('local canonical abort terminates the dedicated worker instead of using the main-thread fallback', async () => {
  const restore = installBrowserWorkerHarness();
  try {
    const client = new SlicerClient();
    const controller = new AbortController();
    const reason = new Error('stop local worker');
    const pending = client.sliceProjectWithRoute(
      new ArrayBuffer(8),
      { kind: 'browser-wasm' },
      {
        signal: controller.signal,
        allowUncancellableMainThreadFallback: false,
      },
    );
    await waitUntil(() => restore.worker?.posted === true);
    controller.abort(reason);
    await assert.rejects(pending, (error: unknown) => error === reason);
    assert.equal(restore.worker?.terminated, true);
  } finally {
    restore.restore();
  }
});

