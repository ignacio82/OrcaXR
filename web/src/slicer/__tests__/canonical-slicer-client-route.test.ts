await test('external canonical abort waits for DELETE cancellation confirmation once a job ID exists', async () => {
  const restore = installExternalHarness();
  try {
    restore.storage.setItem('external_slicer_url', 'http://slicer.local:3000');
    restore.storage.setItem('external_slicer_enabled', 'true');
    let releasePost: ((response: Response) => void) | undefined;
    const postResponse = new Promise<Response>((resolve) => {
      releasePost = resolve;
    });
    restore.fetchImpl = async (request) => {
      restore.requests.push(request);
      const url = new URL(request.url);
      if (request.method === 'POST') return postResponse;
      if (request.method === 'DELETE') {
        return jsonResponse({ status: 'cancelling' }, 202);
      }
      if (url.pathname === '/jobs/job-1') return jsonResponse({ status: 'cancelled', percent: 0 });
      throw new Error(`Unexpected request: ${request.method} ${url.pathname}`);
    };

    const client = new SlicerClient();
    const controller = new AbortController();
    const reason = new Error('stop remote job');
    const pending = client.sliceProjectWithRoute(
      new ArrayBuffer(8),
      { kind: 'external-server', endpoint: 'http://slicer.local:3000' },
      { signal: controller.signal, externalPollIntervalMs: 1, externalCancellationTimeoutMs: 100 },
    );
    await waitUntil(() => restore.requests.some((request) => request.method === 'POST'));
    controller.abort(reason);
    releasePost?.(jsonResponse({ job: 'job-1' }, 202));
    await assert.rejects(pending, (error: unknown) => error === reason);
    assert.ok(restore.requests.some((request) => request.method === 'DELETE' && request.url.endsWith('/jobs/job-1')));
    assert.ok(restore.requests.some((request) => request.method === 'GET' && request.url.endsWith('/jobs/job-1')));
  } finally {
    restore.restore();
  }
});

await test('external async route forwards server progress and returns the completed G-code', async () => {
  const restore = installExternalHarness();
  try {
    restore.storage.setItem('external_slicer_url', 'http://progress.local:3000');
    restore.storage.setItem('external_slicer_enabled', 'true');
    let statusReads = 0;
    restore.fetchImpl = async (request) => {
      restore.requests.push(request);
      const url = new URL(request.url);
      if (request.method === 'POST') return jsonResponse({ job: 'job-progress' }, 202);
      if (url.pathname === '/jobs/job-progress/gcode') return new Response('; complete\nG1 X1\n');
      if (url.pathname === '/jobs/job-progress') {
        statusReads += 1;
        return statusReads === 1
          ? jsonResponse({ status: 'running', percent: 42, message: 'Generating supports' })
          : jsonResponse({ status: 'done', percent: 100 });
      }
      throw new Error(`Unexpected request: ${request.method} ${url.pathname}`);
    };
    const progress: Array<{ percent: number; message: string }> = [];
    const result = await new SlicerClient().sliceProjectWithRoute(
      new ArrayBuffer(8),
      { kind: 'external-server', endpoint: 'http://progress.local:3000' },
      { externalPollIntervalMs: 1, onProgress: (value) => progress.push(value) },
    );
    assert.equal(result, '; complete\nG1 X1\n');
    assert.deepEqual(progress, [
      { percent: 0, message: 'Slicing project externally...' },
      { percent: 42, message: 'Generating supports' },
    ]);
  } finally {
    restore.restore();
  }
});

