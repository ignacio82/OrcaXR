test("rate limits return 429 with Retry-After", async () => {
  const instance = await fixture({ config: { maxRequestsPerWindow: 1 } });
  try {
    assert.equal((await fetch(`${instance.url}/ping`)).status, 200);
    const denied = await fetch(`${instance.url}/ping`);
    assert.equal(denied.status, 429);
    assert(Number(denied.headers.get("retry-after")) >= 1);
  } finally {
    await instance.close();
  }

  const preflightInstance = await fixture({
    config: { maxRequestsPerWindow: 1 },
  });
  try {
    const headers = {
      Origin: "http://localhost:5173",
      "Access-Control-Request-Method": "GET",
    };
    assert.equal(
      (
        await fetch(`${preflightInstance.url}/ping`, {
          method: "OPTIONS",
          headers,
        })
      ).status,
      204,
    );
    assert.equal(
      (
        await fetch(`${preflightInstance.url}/ping`, {
          method: "OPTIONS",
          headers,
        })
      ).status,
      429,
    );
  } finally {
    await preflightInstance.close();
  }
});
