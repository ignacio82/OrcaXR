let seed = 0x5eed1234;
const next = () => {
  seed ^= seed << 13;
  seed ^= seed >>> 17;
  seed ^= seed << 5;
  return (seed >>> 0) / 0x1_0000_0000;
};
const pick = (items) => items[Math.floor(next() * items.length)];
