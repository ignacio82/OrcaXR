// Tool usage, filament slots and tool mapping references from the production
// browser (`PrintToolMappingExchange.ts` over `PrintToolMapping.ts` and
// `MoonrakerFilamentSlots.ts`). Usage cases are artifact bytes, decoded as the
// browser's TextDecoder decodes them (BOM dropped, malformed sequences
// replaced): tool selections at every kind of line start, sentinels and
// malformed numbers, and configuration lines that span lines, repeat or are
// misnamed; seeded artifacts mix them. Slot cases are Snapmaker query replies
// with every loaded-flag spelling, colour form, label hazard and size bound.
// Mapping cases pair the usages with slot sets that match, miss, differ in
// material family or colour, or repeat an index. Replayed by Rust (bytes split
// at many chunk sizes), WASM (Node, Chrome) and JNI.
