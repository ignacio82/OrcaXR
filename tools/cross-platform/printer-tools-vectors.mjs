for (let t = 0; t < 80; t += 1) {
  const parts = [];
  for (let i = 0, n = 2 + Math.floor(next() * 30); i < n; i += 1)
    parts.push(pick(LINES) + pick(BREAKS));
  let bytes = encoder.encode(parts.join(""));
  if (next() < 0.15) bytes = Uint8Array.from([0xef, 0xbb, 0xbf, ...bytes]);
  if (next() < 0.25) {
    const at = Math.floor(next() * bytes.length);
    bytes = Uint8Array.from([
      ...bytes.slice(0, at),
      pick([0xff, 0x80, 0xc3, 0xe2]),
      ...bytes.slice(at),
    ]);
  }
  scan(`seeded-${t}`, bytes);
}

// --- Filament slots -------------------------------------------------------------------
const slots = [];
const slotSets = [];
function slotCase(name, json) {
  const textJson = typeof json === "string" ? json : JSON.stringify(json);
  const reply = answerFilamentSlots(JSON.parse(textJson));
  if ("slots" in reply) slotSets.push(reply.slots);
  slots.push({
    name,
    text: textJson,
    replyJson: encodeProjectFilamentSlotsReply(reply),
  });
}
