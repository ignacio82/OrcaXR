// The pinned `filament_mixer` polynomial for the Rust core
// (`orcaxr_project::filaments::mixer_model`), generated from the browser's
// table (`web/src/project/filaments/filamentMixerModel.ts`) so both evaluate
// the same doubles. Each coefficient is written as JavaScript's shortest
// round-trip text, which Rust parses back to the same binary64.
// `--write` regenerates; without it the committed table is checked.
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import {
  COEF,
  INTERCEPT,
  N_FEATURES,
  N_INPUTS,
  POWERS,
} from "../../web/src/project/filaments/filamentMixerModel.ts";

const root = new URL("../../", import.meta.url);
assert.ok(process.argv.slice(2).every((v) => v === "--write"));
const source = "web/src/project/filaments/filamentMixerModel.ts";
assert.equal(POWERS.length, N_FEATURES * N_INPUTS);
assert.equal(COEF.length, N_FEATURES * 3);
assert.equal(INTERCEPT.length, 3);

const float = (value) => {
  assert.ok(Number.isFinite(value));
  const text = String(value);
  return /[.e]/.test(text) ? text : `${text}.0`;
};
const rows = (values, format, perLine) => {
  const lines = [];
  for (let i = 0; i < values.length; i += perLine)
    lines.push(`    ${values.slice(i, i + perLine).map(format).join(", ")},`);
  return lines.join("\n");
};
const digest = createHash("sha256").update(readFileSync(new URL(source, root))).digest("hex");
const rust =
  `// Generated by tools/cross-platform/generate-filament-mixer.mjs from\n` +
  `// ${source} (sha256 ${digest}).\n` +
  `// Do not edit; regenerate when the pinned model changes.\n` +
  `pub(crate) const N_FEATURES: usize = ${N_FEATURES};\n` +
  `pub(crate) const N_INPUTS: usize = ${N_INPUTS};\n` +
  `#[rustfmt::skip]\npub(crate) const POWERS: [u8; ${POWERS.length}] = [\n${rows(POWERS, String, 28)}\n];\n` +
  `#[rustfmt::skip]\npub(crate) const COEF: [f64; ${COEF.length}] = [\n${rows(COEF, float, 4)}\n];\n` +
  `#[rustfmt::skip]\npub(crate) const INTERCEPT: [f64; 3] = [${INTERCEPT.map(float).join(", ")}];\n`;
const path = new URL("core/crates/orcaxr-project/src/filaments/mixer_model.rs", root);
if (process.argv.includes("--write")) writeFileSync(path, rust);
else assert.equal(readFileSync(path, "utf8"), rust, "Generated filament mixer drift");
console.log(`Filament mixer: ${N_FEATURES} features, ${COEF.length} coefficients.`);
