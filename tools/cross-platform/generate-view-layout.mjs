import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
const root = new URL("../../", import.meta.url);
const schema = JSON.parse(
  readFileSync(new URL("contracts/gcode-view-buffer.json", root)),
);
assert.deepEqual(
  Object.keys(schema).sort(),
  [
    "version",
    "magic",
    "byteOrder",
    "alignment",
    "header",
    "maxMetadataBytes",
    "maxPacketBytes",
    "maxRequestBytes",
    "maxRecords",
    "maxLayers",
    "maxTicks",
    "kinds",
    "tickKinds",
    "textEncoding",
  ].sort(),
);
assert.equal(schema.version, 1);
assert.equal(schema.magic, "OXGV");
assert.equal(schema.byteOrder, "little");
assert.equal(schema.alignment, 4);
assert.equal(schema.textEncoding, "utf16-code-units");
assert.deepEqual(schema.header, [
  "magic",
  "version",
  "kind",
  "metadataBytes",
  "records",
  "layers",
  "ticks",
  "totalBytes",
]);
const kinds = {
  u8: ["Uint8Array", 1],
  u32: ["Uint32Array", 4],
  f32: ["Float32Array", 4],
};
const snake = (s) => s.replace(/[A-Z]/g, (c) => "_" + c.toLowerCase());
const constants = Object.fromEntries(
  Object.entries(schema).filter(([, v]) => typeof v === "number"),
);
for (const value of Object.values(constants))
  assert.ok(Number.isSafeInteger(value) && value > 0 && value < 0x7fffffff);
const header =
  "// Generated by tools/cross-platform/generate-view-layout.mjs. Do not edit.\n";
let rust =
  header +
  "#[derive(Clone,Copy,Debug)]\npub struct Field {pub name: &'static str, pub kind: &'static str, pub bytes: usize, pub counter: usize, pub factor: usize}\n";
let kotlin = header + "package dev.orcaxr.core\n\nobject GcodeViewLayout {\n";
for (const [name, value] of Object.entries(constants)) {
  rust += `pub const ${snake(name).toUpperCase()}: usize = ${value};\n`;
  kotlin += `    const val ${snake(name).toUpperCase()} = ${value}\n`;
}
let ts =
  header +
  `export const GCODE_VIEW_LAYOUT = ${JSON.stringify(schema, null, 2)} as const;\nexport const GCODE_VIEW_FIELDS = {\n`;
kotlin +=
  "    data class Field(val name: String, val type: String, val bytes: Int, val counter: Int, val factor: Int)\n    val fields = mapOf(\n";
for (const [name, kind] of Object.entries(schema.kinds)) {
  assert.match(name, /^[a-z]+$/);
  assert.deepEqual(Object.keys(kind).sort(), ["fields", "id"]);
  assert.ok(Number.isSafeInteger(kind.id) && kind.id > 0);
  assert.equal(new Set(kind.fields.map((f) => f[0])).size, kind.fields.length);
  rust += `pub const ${name.toUpperCase()}: usize = ${kind.id};\npub const ${name.toUpperCase()}_FIELDS: &[Field] = &[\n`;
  kotlin += `        ${kind.id} to listOf(\n`;
  ts += `  ${kind.id}: [\n`;
  for (const [field, type, counter, factor] of kind.fields) {
    assert.match(field, /^[a-z][A-Za-z0-9]*$/);
    assert.ok(kinds[type]);
    assert.ok(["records", "layers", "ticks"].includes(counter));
    assert.ok(Number.isSafeInteger(factor) && factor > 0 && factor <= 4);
    const n = ["records", "layers", "ticks"].indexOf(counter),
      bytes = kinds[type][1];
    rust += `Field {name: "${field}", kind: "${type}", bytes: ${bytes}, counter: ${n}, factor: ${factor}},\n`;
    ts += `{name: '${field}', type: '${type}', bytes: ${bytes}, counter: ${n}, factor: ${factor}, ArrayType: ${kinds[type][0]}},\n`;
    kotlin += `            Field("${field}", "${type}", ${bytes}, ${n}, ${factor}),\n`;
  }
  rust += "];\n";
  kotlin += "        ),\n";
  ts += "  ],\n";
}
assert.deepEqual(
  Object.values(schema.kinds).map((v) => v.id),
  [1, 2, 3],
);
assert.deepEqual(schema.tickKinds, {
  4: "tool-change",
  5: "color-change",
  6: "pause",
  7: "custom",
});
rust +=
  "pub fn fields(kind: usize) -> Option<&'static [Field]> {match kind {\n" +
  Object.entries(schema.kinds)
    .map(
      ([name, kind]) => `${kind.id} => Some(${name.toUpperCase()}_FIELDS),\n`,
    )
    .join("") +
  "_ => None}}\n";
kotlin +=
  '    )\n    val tickKinds = mapOf(4 to "tool-change", 5 to "color-change", 6 to "pause", 7 to "custom")\n}\n';
ts += "} as const;\n";
const formatted = spawnSync("rustfmt", ["+1.94.1", "--edition", "2024"], {
  input: rust,
  encoding: "utf8",
});
assert.equal(formatted.status, 0, formatted.stderr);
for (const [path, content] of [
  ["core/crates/orcaxr-gcode/src/view_layout.rs", formatted.stdout],
  ["contracts/generated/gcode-view-layout.ts", ts],
  [
    "android/core-bridge/src/main/java/dev/orcaxr/core/GcodeViewLayout.kt",
    kotlin,
  ],
]) {
  const file = new URL(path, root);
  if (process.argv.includes("--write")) writeFileSync(file, content);
  else assert.equal(readFileSync(file, "utf8"), content, `${path} drifted`);
}
console.log("Verified Rust/TypeScript/Kotlin G-code view packet descriptors");
