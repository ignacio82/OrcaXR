// Versioned bulk command input. JSON arrays use numeric tags from ordered maps;
// records retain persisted JSON semantics rather than the small intent decoder.
import assert from "node:assert/strict";
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { tmpdir } from "node:os";
import { join } from "node:path";
const root = new URL("../../", import.meta.url);
const s = JSON.parse(
  readFileSync(new URL("contracts/project-staging.json", root)),
);
assert.deepEqual(
  Object.keys(s).sort(),
  [
    "version",
    "maxPreparations",
    "maxClipboards",
    "envelope",
    "inputOptions",
    "poolOptions",
    "clipboardOptions",
    "clipboardInfo",
    "workKinds",
    "commandKinds",
  ].sort(),
);
assert.equal(s.version, 1);
assert.deepEqual(s.envelope, ["version", "work"]);
assert.deepEqual(Object.keys(s.workKinds), [
  "single",
  "transaction",
  "splitToObjects",
]);
assert.deepEqual(Object.keys(s.commandKinds), [
  "createInstance",
  "pasteObject",
  "intent",
  "clipboardPaste",
  "addObject",
  "addObjectWithAsset",
  "addVolume",
  "replaceVolumeMesh",
  "meshBoolean",
  "splitVolumeToParts",
  "addSvgPart",
  "editSvgPart",
  "addEmbossText",
  "editEmbossText",
  "replaceProject",
]);
assert.ok(
  Number.isSafeInteger(s.maxPreparations) &&
    s.maxPreparations > 0 &&
    s.maxPreparations <= 32,
);
assert.ok(
  Number.isSafeInteger(s.maxClipboards) &&
    s.maxClipboards > 0 &&
    s.maxClipboards <= 32,
);
assert.deepEqual(s.clipboardInfo, [
  "volumes",
  "instances",
  "layerRanges",
  "assets",
  "bytes",
]);
assert.deepEqual(s.clipboardOptions, ["assets", "bytes"]);
assert.deepEqual(s.inputOptions, [
  "bytes",
  "nodes",
  "textUnits",
  "numberBytes",
  "depth",
  "commands",
  "inputUnits",
  "assets",
  "assetBytes",
]);
assert.deepEqual(s.poolOptions, [
  "resources",
  "commands",
  "inputUnits",
  "assetBytes",
]);
assert.deepEqual(s.workKinds, {
  single: ["command"],
  transaction: ["label", "commands"],
  splitToObjects: ["guard", "parts", "identities"],
});
assert.deepEqual(s.commandKinds, {
  createInstance: ["objectId", "record", "index"],
  pasteObject: [
    "record",
    "objectId",
    "volumeIds",
    "instanceIds",
    "layerRangeIds",
    "destination",
    "name",
  ],
  intent: ["asciiJson"],
  clipboardPaste: [
    "objectId",
    "volumeIds",
    "instanceIds",
    "layerRangeIds",
    "destination",
  ],
  addObject: ["plateId", "record"],
  addObjectWithAsset: ["plateId", "record", "descriptor"],
  addVolume: ["objectId", "record", "descriptor"],
  replaceVolumeMesh: ["guard", "descriptor"],
  meshBoolean: ["guard", "descriptor", "op"],
  splitVolumeToParts: ["guard", "parts"],
  addSvgPart: [
    "placement",
    "descriptor",
    "drawing",
    "triangleCount",
    "part",
    "name",
  ],
  editSvgPart: ["volumeId", "descriptor", "triangleCount", "part"],
  addEmbossText: ["placement", "configuration", "descriptor", "triangleCount"],
  editEmbossText: ["volumeId", "configuration", "descriptor", "triangleCount"],
  replaceProject: ["state", "label"],
});
const snake = (n) => n.replace(/[A-Z]/g, (c) => "_" + c.toLowerCase());
const header =
  "// Generated by tools/cross-platform/generate-project-staging.mjs. Do not edit.\n";
let rs =
  header + "use crate::host_layout::{MAX_BUDGET, MAX_SUPPORTED_DEPTH};\n";
rs += `pub const VERSION: usize = ${s.version};\npub const MAX_PREPARATIONS: usize = ${s.maxPreparations};\npub const ENVELOPE_LENGTH: usize = ${s.envelope.length};\n`;
rs += `pub const MAX_CLIPBOARDS: usize = ${s.maxClipboards};\npub const CLIPBOARD_INFO_LENGTH: usize = ${s.clipboardInfo.length};\n`;
for (const [i, key] of s.clipboardInfo.entries())
  rs += `pub const CLIPBOARD_${snake(key).toUpperCase()}: usize = ${i};\n`;
for (const [prefix, variants] of [
  ["WORK", s.workKinds],
  ["COMMAND", s.commandKinds],
])
  for (const [i, [kind, fields]] of Object.entries(variants).entries()) {
    rs += `pub const ${prefix}_${snake(kind).toUpperCase()}: usize = ${i};\n`;
    rs += `pub const ${prefix}_${snake(kind).toUpperCase()}_LENGTH: usize = ${fields.length + 1};\n`;
  }
let ts =
  header +
  `import { PROJECT_HOST } from './project-host';\nexport const PROJECT_STAGING = ${JSON.stringify(s, null, 2)} as const;\n`;
let kt =
  header +
  "package dev.orcaxr.core\n\nobject ProjectStaging {\n" +
  `    const val VERSION = ${s.version}\n    const val MAX_PREPARATIONS = ${s.maxPreparations}\n`;
kt += `    const val MAX_CLIPBOARDS = ${s.maxClipboards}\n    const val CLIPBOARD_INFO_LENGTH = ${s.clipboardInfo.length}\n`;
for (const [i, key] of s.clipboardInfo.entries())
  kt += `    const val CLIPBOARD_${snake(key).toUpperCase()} = ${i}\n`;
for (const [prefix, variants] of [
  ["WORK", s.workKinds],
  ["COMMAND", s.commandKinds],
])
  for (const [i, kind] of Object.keys(variants).entries())
    kt += `    const val ${prefix}_${snake(kind).toUpperCase()} = ${i}\n`;
kt += "}\n";
for (const [name, keys] of [
  ["Input", s.inputOptions],
  ["Pool", s.poolOptions],
  ["Clipboard", s.clipboardOptions],
]) {
  rs += `#[derive(Debug, Clone, Copy)]\npub struct ${name}Options {\n`;
  for (const k of keys) rs += `    pub ${snake(k)}: usize,\n`;
  rs += `}\npub fn decode_${name.toLowerCase()}(version: f64, input: &[f64]) -> Option<${name}Options> {\n`;
  rs += `    if version != VERSION as f64 || input.len() != ${keys.length} || input.iter().any(|v| !v.is_finite() || v.fract() != 0.0 || *v < 0.0 || *v > MAX_BUDGET as f64) { return None; }\n`;
  if (name === "Input")
    rs +=
      "    if input[4] > MAX_SUPPORTED_DEPTH as f64 || input[3] == 0.0 { return None; }\n";
  rs +=
    `    Some(${name}Options {\n` +
    keys
      .map((k, i) => `        ${snake(k)}: input[${i}] as usize,\n`)
      .join("") +
    "    })\n}\n";
  ts +=
    `export interface ProjectStaging${name}Options {\n` +
    keys.map((k) => `  readonly ${k}: number;\n`).join("") +
    "}\n";
  ts += `export function encodeProjectStaging${name}Options(value: ProjectStaging${name}Options): Float64Array {\n`;
  ts += `  const fields = PROJECT_STAGING.${name.toLowerCase()}Options;\n  const keys = Reflect.ownKeys(value);\n  if (keys.length !== fields.length || keys.some(k => typeof k !== 'string' || !(fields as readonly string[]).includes(k))) throw new Error('Invalid staging options');\n  const values = fields.map(k => {\n    const d = Object.getOwnPropertyDescriptor(value, k);\n    const n: unknown = d?.value;\n    if (!d || !('value' in d) || typeof n !== 'number' || !Number.isInteger(n) || n < 0 || n > PROJECT_HOST.maxBudget) throw new Error('Invalid staging options');\n    return n;\n  });\n`;
  if (name === "Input")
    ts += `  if (values[4]! > PROJECT_HOST.maxSupportedDepth || values[3] === 0) throw new Error('Invalid staging options');\n`;
  ts += "  return new Float64Array(values);\n}\n";
  kt +=
    `\ndata class ProjectStaging${name}Options(\n` +
    keys.map((k) => `    val ${k}: Long,\n`).join("") +
    ") {\n    fun encode(): DoubleArray {\n";
  kt += `        val values = longArrayOf(${keys.join(", ")})\n        require(values.all { it in 0..ProjectHost.MAX_BUDGET }${name === "Input" ? " && depth <= ProjectHost.MAX_SUPPORTED_DEPTH && numberBytes > 0" : ""}) { "Invalid staging options" }\n        return values.map { it.toDouble() }.toDoubleArray()\n    }\n}\n`;
}
const directory = mkdtempSync(join(tmpdir(), "orcaxr-staging-codegen-"));
try {
  const file = join(directory, "staging.rs");
  writeFileSync(file, rs);
  const formatted = spawnSync(
    "rustfmt",
    ["+1.94.1", "--edition", "2024", file],
    { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] },
  );
  assert.equal(formatted.status, 0, formatted.stderr);
  rs = readFileSync(file, "utf8");
} finally {
  rmSync(directory, { recursive: true, force: true });
}
for (const [path, content] of [
  ["core/crates/orcaxr-project/src/staging_layout.rs", rs],
  ["contracts/generated/project-staging.ts", ts],
  ["android/core-bridge/src/main/java/dev/orcaxr/core/ProjectStaging.kt", kt],
]) {
  const url = new URL(path, root);
  if (process.argv.includes("--write")) writeFileSync(url, content);
  else
    assert.equal(
      readFileSync(url, "utf8"),
      content,
      `${path} requires regeneration`,
    );
}
console.log("Verified staged command upload shapes, tags and options");
