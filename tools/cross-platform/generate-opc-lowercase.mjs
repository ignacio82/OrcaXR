// Pin persisted package-name casing independently of browser/Rust Unicode upgrades.
import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
const root = new URL("../../", import.meta.url),
  path = new URL("contracts/opc-lowercase.json", root);
const args = new Set(process.argv.slice(2));
assert.ok(
  [...args].every((a) =>
    ["--write", "--capture", "--verify-runtime"].includes(a),
  ),
);
const units = (s) =>
  Array.from({ length: s.length }, (_, i) => s.charCodeAt(i));
if (args.has("--capture") || args.has("--verify-runtime")) {
  assert.equal(
    process.versions.unicode,
    "16.0",
    "Capture requires the established Unicode 16.0 browser baseline",
  );
  const lower = [],
    cased = [],
    ignorable = [];
  const casedRe = /\p{Cased}/u,
    ignoreRe = /\p{Case_Ignorable}/u;
  const addRange = (ranges, cp) => {
    const last = ranges.at(-1);
    if (last && last[1] === cp - 1) last[1] = cp;
    else ranges.push([cp, cp]);
  };
  for (let cp = 0; cp <= 0x10ffff; cp++) {
    if (cp >= 0xd800 && cp <= 0xdfff) continue;
    const s = String.fromCodePoint(cp),
      out = s.toLowerCase();
    if (out !== s) lower.push([cp, Array.from(out, (c) => c.codePointAt(0))]);
    if (casedRe.test(s)) addRange(cased, cp);
    if (ignoreRe.test(s)) addRange(ignorable, cp);
  }
  const points = new Set([
    0, 0xd800, 0xdfff, 0x130, 0x3a3, 0x345, 0x2b0, 0x10ffff,
  ]);
  for (const ranges of [cased, ignorable])
    for (const [a, b] of ranges)
      for (const cp of [a - 1, a, b, b + 1])
        if (cp >= 0 && cp <= 0x10ffff) points.add(cp);
  const contexts = new Set([
    "AΣ",
    "AΣA",
    "Σ",
    "ΣΣ",
    "A\u0345Σ",
    "\u02b0Σ",
    "AΣ\u02b0",
    "\ud800AΣ\udfff",
  ]);
  for (const cp of [...points].sort((a, b) => a - b)) {
    const s = String.fromCodePoint(cp);
    for (const v of [`A${s}Σ`, `AΣ${s}`, `${s}Σ`, `Σ${s}A`, `A${s}Σ${s}`])
      contexts.add(v);
  }
  const data = {
    schemaVersion: 1,
    unicodeVersion: "16.0.0",
    authority:
      "Node/V8 Unicode 16.0 default String.prototype.toLowerCase and Cased/Case_Ignorable properties",
    lower,
    cased,
    ignorable,
    contexts: [...contexts].map((s) => ({
      input: units(s),
      output: units(s.toLowerCase()),
    })),
  };
  const text = JSON.stringify(data, null, 2) + "\n";
  if (args.has("--capture")) writeFileSync(path, text);
  else
    assert.equal(
      readFileSync(path, "utf8"),
      text,
      "Pinned Unicode data differs from the reference runtime",
    );
}
const data = JSON.parse(readFileSync(path, "utf8"));
assert.equal(data.schemaVersion, 1);
assert.equal(data.unicodeVersion, "16.0.0");
const scalar = (n) =>
  Number.isInteger(n) &&
  n >= 0 &&
  n <= 0x10ffff &&
  !(n >= 0xd800 && n <= 0xdfff);
let last = -1;
for (const [cp, output] of data.lower) {
  assert.ok(
    scalar(cp) && cp > last && output.length > 0 && output.every(scalar),
  );
  last = cp;
}
for (const ranges of [data.cased, data.ignorable]) {
  let last = -1;
  for (const [a, b] of ranges) {
    assert.ok(scalar(a) && scalar(b) && a <= b && a > last + 1);
    last = b;
  }
}
// Compress simple mappings into disjoint step-1/step-2 delta runs.
const simple = [],
  expansions = [];
for (let i = 0; i < data.lower.length;) {
  const [cp, out] = data.lower[i];
  if (out.length !== 1) {
    expansions.push([cp, out]);
    i++;
    continue;
  }
  const delta = out[0] - cp;
  let end = i,
    step = 1;
  if (i + 1 < data.lower.length) {
    const [next, mapped] = data.lower[i + 1];
    if (
      mapped.length === 1 &&
      mapped[0] - next === delta &&
      (next - cp === 1 || next - cp === 2)
    ) {
      step = next - cp;
      end++;
      while (end + 1 < data.lower.length) {
        const [next, mapped] = data.lower[end + 1];
        if (
          mapped.length !== 1 ||
          mapped[0] - next !== delta ||
          next - data.lower[end][0] !== step
        )
          break;
        end++;
      }
    }
  }
  simple.push([cp, data.lower[end][0], step, delta]);
  i = end + 1;
}
const note =
  "Generated by tools/cross-platform/generate-opc-lowercase.mjs. Unicode 16.0; see NOTICE.md.";
const rust =
  `// ${note}\n#[rustfmt::skip]\npub(super) const LOWER:&[(u32,u32,u32,i32)]=&[\n${simple.map((r) => `    (${r.join(",")}),`).join("\n")}\n];\n#[rustfmt::skip]\npub(super) const EXPANSIONS:&[(u32,&[u32])]=&[${expansions.map(([cp, v]) => `(${cp},&[${v}])`).join(",")}];\n` +
  [
    ["CASED", data.cased],
    ["IGNORABLE", data.ignorable],
  ]
    .map(
      ([name, rows]) =>
        `#[rustfmt::skip]\npub(super) const ${name}:&[(u32,u32)]=&[\n${rows.map((r) => `    (${r}),`).join("\n")}\n];\n`,
    )
    .join("");
const ts =
  `// ${note}\n` +
  [
    ["LOWER", simple, "[number, number, number, number]"],
    ["EXPANSIONS", expansions, "[number, readonly number[]]"],
    ["CASED", data.cased, "[number, number]"],
    ["IGNORABLE", data.ignorable, "[number, number]"],
  ]
    .map(
      ([name, rows, type]) =>
        `// prettier-ignore\nexport const ${name}: readonly (readonly ${type})[] = ${JSON.stringify(rows)};\n`,
    )
    .join("");
for (const [name, text] of [
  ["core/crates/orcaxr-project/src/js_math/case_data.rs", rust],
  ["web/src/project/serialization/opcCaseData.ts", ts],
]) {
  const p = new URL(name, root);
  if (args.has("--write") || args.has("--capture")) writeFileSync(p, text);
  else
    assert.equal(
      readFileSync(p, "utf8"),
      text,
      `Generated OPC casing drift: ${name}`,
    );
}
console.log(
  `OPC casing: ${data.lower.length} mappings (${simple.length} delta runs), ${data.contexts.length} contexts`,
);
