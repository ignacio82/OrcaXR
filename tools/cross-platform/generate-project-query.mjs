for (const [path, value] of [
  ["core/crates/orcaxr-project/src/query/layout.rs", rust],
  ["contracts/generated/project-query.ts", ts],
  ["android/core-bridge/src/main/java/dev/orcaxr/core/ProjectQuery.kt", kotlin],
]) {
  const url = new URL(path, root);
  if (process.argv.includes("--write")) writeFileSync(url, value);
  else assert.equal(readFileSync(url, "utf8"), value, `Regenerate ${path}`);
}
console.log(
  `Verified project query layout: ${kinds.length} node kinds, ${relations.length} relations`,
);
