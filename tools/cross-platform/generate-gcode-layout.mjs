import assert from 'node:assert/strict';
import {readFileSync, writeFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
const root = new URL('../../', import.meta.url);
const schema = JSON.parse(readFileSync(new URL('contracts/gcode-buffer.json', root)));
assert.deepEqual(Object.keys(schema).sort(), ['version','magic','byteOrder','alignment','header','maxMetadataBytes','maxPacketBytes','maxChunkUnits','maxIndexPageEntries','maxWindowRecords','maxPathPoints','maxTextWindowLines','maxTextWindowUnits','maxSearchResults','maxSearchLimit','maxQueryUnits','columns','pathColumns','textEncoding'].sort());
assert.equal(schema.magic, 'OXGP');
assert.equal(schema.byteOrder, 'little');
assert.equal(schema.alignment, 4);
assert.equal(schema.textEncoding, 'utf16-code-units');
assert.deepEqual(schema.header, ['magic','version','metadataBytes','records','pathPoints','totalBytes']);
const constants = Object.fromEntries(Object.entries(schema).filter(([, v]) => typeof v === 'number'));
for (const value of Object.values(constants)) assert.ok(Number.isSafeInteger(value) && value > 0 && value < 0x7fffffff);
const kinds = {u8: ['Uint8Array',1], u16: ['Uint16Array',2], u32: ['Uint32Array',4], i32: ['Int32Array',4], f32: ['Float32Array',4]};
const fields = Object.entries(schema.columns).map(([name, type]) => ({group:'columns',name,type})).concat(Object.entries(schema.pathColumns).map(([name,type]) => ({group:'pathPoints',name,type})));
const snake = s => s.replace(/[A-Z]/g, c => '_'+c.toLowerCase());
for (const {name,type} of fields) { assert.match(name, /^[a-z][A-Za-z0-9]*$/); assert.ok(kinds[type]); }
const header = '// Generated by tools/cross-platform/generate-gcode-layout.mjs. Do not edit.\n';
let rust = header;
for (const [name,value] of Object.entries(constants)) rust += `pub const ${snake(name).toUpperCase()}: usize = ${value};\n`;
rust += 'pub fn columns_bytes(records: usize, points: usize) -> Option<usize> { let mut total = 0usize;\n';
for (const {group,type} of fields) rust += `total = total.checked_add(${group === 'columns' ? 'records' : 'points'}.checked_mul(${kinds[type][1]})?.checked_add(3)? & !3)?;\n`;
rust += 'Some(total) }\npub fn valid_lengths(model: &crate::Model) -> bool {\n';
rust += fields.map(({group,name}) => `model.${snake(group)}.${snake(name)}.len() == model.${snake(group)}.count`).join(' &&\n');
rust += '\n}\npub fn write_columns(model: &crate::Model, output: &mut Vec<u8>, cancel: &crate::Cancellation) -> Result<(), crate::SessionError> {\n';
for (const {group,name} of fields) rust += `for chunk in model.${snake(group)}.${snake(name)}.chunks(4096) { if cancel.is_cancelled() { return Err(crate::SessionError::Cancelled); } for value in chunk { output.extend_from_slice(&value.to_le_bytes()); } }\nwhile !output.len().is_multiple_of(4) {output.push(0);}\n`;
rust += 'Ok(())}\n';
const formatted = spawnSync('rustfmt',['+1.94.1','--edition','2024'],{input:rust,encoding:'utf8'});
assert.equal(formatted.status,0,formatted.stderr);
let ts = header + `export const GCODE_LAYOUT = ${JSON.stringify(schema,null,2)} as const;\n`;
ts += 'export const GCODE_FIELDS = [\n';
for (const {group,name,type} of fields) ts += `  {group: '${group}', name: '${name}', type: '${type}', bytes: ${kinds[type][1]}, ArrayType: ${kinds[type][0]}},\n`;
ts += '] as const;\n';
let kotlin = header + 'package dev.orcaxr.core\n\nobject GcodeLayout {\n';
for (const [name,value] of Object.entries(constants)) kotlin += `    const val ${snake(name).toUpperCase()} = ${value}\n`;
kotlin += '    data class Field(val group: String, val name: String, val type: String, val bytes: Int)\n    val fields = listOf(\n';
for (const {group,name,type} of fields) kotlin += `        Field("${group}", "${name}", "${type}", ${kinds[type][1]}),\n`;
kotlin += '    )\n}\n';
for (const [name,content] of [['core/crates/orcaxr-gcode/src/layout.rs',formatted.stdout], ['contracts/generated/gcode-layout.ts',ts], ['android/core-bridge/src/main/java/dev/orcaxr/core/GcodeLayout.kt',kotlin]]) {
  const path = new URL(name,root);
  if (process.argv.includes('--write')) writeFileSync(path,content);
  else assert.equal(readFileSync(path,'utf8'),content,`${name} requires regeneration`);
}
console.log('Verified shared Rust/TypeScript/Kotlin G-code buffer layout');
