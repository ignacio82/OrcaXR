// Commit a verified Rust WASM/glue pair so normal web builds need no Rust SDK.
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFileSync, readdirSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve, relative } from "node:path";
import { fileURLToPath } from "node:url";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const hash = (bytes) => createHash("sha256").update(bytes).digest("hex");
const read = (path) => readFileSync(resolve(root, path));
const json = (path) => JSON.parse(read(path));
const walk = (directory) =>
  readdirSync(resolve(root, directory), { withFileTypes: true }).flatMap(
    (entry) =>
      entry.isDirectory()
        ? walk(`${directory}/${entry.name}`)
        : [`${directory}/${entry.name}`],
  );
function inputs() {
  const paths = [
    "core/Cargo.toml",
    "core/Cargo.lock",
    "core/rust-toolchain.toml",
    ...walk("core/crates").filter((p) => /\.(rs|toml)$/.test(p)),
    ...walk("contracts").filter((p) => p.endsWith(".json")),
    ...walk("tools/cross-platform").filter((p) => p.endsWith(".py")),
  ];
  return Object.fromEntries(paths.sort().map((p) => [p, hash(read(p))]));
}
const writing = process.argv.includes("--write");
const project = process.argv.includes("--project");
const browserRoot = project ? "core/browser/project" : "core/browser";
const distRoot = project ? "core/dist/project-wasm" : "core/dist/wasm";
const manifest = json(
  writing
    ? `${distRoot}/core-wasm-manifest.json`
    : `${browserRoot}/core-wasm-manifest.json`,
);
assert.equal(manifest.schemaVersion, 1);
assert.equal(manifest.kind, project ? "browser-project-wasm" : "browser-wasm");
assert.deepEqual(manifest.features, project ? ["project"] : ["gcode"]);
assert.equal(manifest.defaultFeatures, !project);
assert.deepEqual(
  manifest.inputs,
  inputs(),
  "Shared core source drift; rebuild then package --write",
);
const names = [
  "orcaxr_core.js",
  "orcaxr_core.d.ts",
  "orcaxr_core_bg.wasm",
  "orcaxr_core_bg.wasm.d.ts",
];
assert.deepEqual(Object.keys(manifest.outputs).sort(), names.toSorted());
const manifestText = JSON.stringify(manifest, null, 2) + "\n";
const setId = hash(manifestText);
const publicPrefix = project ? "core-project" : "core";
const publicRoot = `web/public/${publicPrefix}/${setId}`;
const sourceRoot = writing ? distRoot : browserRoot;
const bytes = Object.fromEntries(
  names.map((name) => {
    const path =
      !writing && name.endsWith(".wasm")
        ? `${publicRoot}/${name}`
        : `${sourceRoot}/${name}`;
    const data = read(path);
    assert.equal(
      hash(data),
      manifest.outputs[name],
      `Mismatched core artifact: ${name}`,
    );
    return [name, data];
  }),
);
// 2026-10-09: raised from 8 MiB. The project core now carries the printer
// policy too, including WHATWG URL parsing (`url`, with ICU4X IDNA, so an
// internationalized printer hostname normalizes as the browser's does). The
// set measured 8,029,290 bytes before the printer workflow port and 8,544,870
// with the transport policy; the unicode-rs IDNA backend measured larger
// (8,672,103) and an ASCII-only one still exceeded the old bound (8,412,458).
assert.ok(
  bytes["orcaxr_core_bg.wasm"].length < 10 * 1024 * 1024,
  "Core executable exceeds its package bound",
);
const asset = {
  setId,
  manifest: {
    path: `${publicPrefix}/${setId}/core-wasm-manifest.json`,
    sha256: setId,
    bytes: Buffer.byteLength(manifestText),
  },
  wasm: {
    path: `${publicPrefix}/${setId}/orcaxr_core_bg.wasm`,
    sha256: manifest.outputs["orcaxr_core_bg.wasm"],
    bytes: bytes["orcaxr_core_bg.wasm"].length,
  },
};
const products = {
  [`${browserRoot}/package.json`]: '{"private":true,"type":"module"}\n',
  [`${browserRoot}/core-wasm-manifest.json`]: manifestText,
  [`${browserRoot}/asset.ts`]:
    `// Generated by tools/cross-platform/package-browser-core.mjs. Do not edit.\nexport const ${project ? "CORE_PROJECT_ASSET" : "CORE_BROWSER_ASSET"} = ` +
    JSON.stringify(asset, null, 2) +
    " as const;\n",
  [`${publicRoot}/core-wasm-manifest.json`]: manifestText,
  [`${publicRoot}/orcaxr_core_bg.wasm`]: bytes["orcaxr_core_bg.wasm"],
  ...Object.fromEntries(
    names
      .filter((name) => !name.endsWith(".wasm"))
      .map((name) => [`${browserRoot}/${name}`, bytes[name]]),
  ),
};
for (const [path, expected] of Object.entries(products)) {
  const file = resolve(root, path);
  assert.ok(relative(root, file) === path);
  if (writing) {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, expected);
  } else
    assert.deepEqual(
      read(path),
      Buffer.from(expected),
      `Packaged core drift: ${path}`,
    );
}
console.log(
  `Verified ${project ? "project" : "computation"} browser core set ${setId.slice(0, 12)} (${asset.wasm.bytes} WASM bytes)`,
);
