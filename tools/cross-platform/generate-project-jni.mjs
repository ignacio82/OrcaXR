// Generate mechanical exports from the Java JNI declarations. Domain behavior
// stays in Rust handlers. Fail on unsupported types or declaration syntax.
import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
const root = new URL("../../", import.meta.url);
const source = readFileSync(
  new URL(
    "android/core-bridge/src/main/java/dev/orcaxr/core/NativeProject.java",
    root,
  ),
  "utf8",
);
const input = {
  int: "jint",
  long: "jlong",
  boolean: "jboolean",
  String: "JString<'local>",
  "byte[]": "JByteArray<'local>",
  "char[]": "JCharArray<'local>",
  "double[]": "JDoubleArray<'local>",
  "long[]": "JLongArray<'local>",
  LocalTimestampResolver: "JObject<'local>",
  ProjectJsonSink: "JObject<'local>",
  PresetCollator: "JObject<'local>",
  SearchFolding: "JObject<'local>",
};
const output = {
  int: "jint",
  long: "jlong",
  boolean: "jboolean",
  void: "()",
  String: "jstring",
  "byte[]": "jbyteArray",
  "char[]": "jcharArray",
  "double[]": "jdoubleArray",
};
const snake = (name) => name.replace(/[A-Z]/g, (c) => "_" + c.toLowerCase());
let rust =
  "// Generated by tools/cross-platform/generate-project-jni.mjs. Do not edit.\nuse super::*;\n";
const declarations = [
  ...source.matchAll(/^    static native ([\w\[\]]+) (\w+)\(([^)]*)\);$/gm),
];
assert.equal(
  declarations.length,
  (source.match(/static native/g) ?? []).length,
);
assert.ok(declarations.length > 0);
const names = new Set();
for (const [, result, name, text] of declarations) {
  assert.ok(!names.has(name));
  names.add(name);
  assert.ok(Object.hasOwn(output, result), result);
  const args = text ? text.split(", ").map((a) => a.split(" ")) : [];
  for (const [type, name] of args) {
    assert.ok(Object.hasOwn(input, type), type);
    assert.match(name, /^[a-z][a-zA-Z0-9]*$/);
  }
  rust += `\nexport! {\n    Java_dev_orcaxr_core_NativeProject_${name}, ${snake(name)}, ${output[result]},\n`;
  for (const [type, name] of args)
    rust += `    ${snake(name)}: ${input[type]},\n`;
  rust += "}\n";
}
const target = new URL(
  "core/crates/orcaxr-android/src/project/bindings.rs",
  root,
);
if (process.argv.includes("--write")) writeFileSync(target, rust);
else
  assert.equal(
    readFileSync(target, "utf8"),
    rust,
    "Regenerate project JNI exports",
  );
console.log(`Verified ${declarations.length} project JNI exports`);
