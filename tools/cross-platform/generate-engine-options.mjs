// Generate the native engine-option tables from the browser's pinned schema,
// admitted by its own production validator: the storage contract, bounds and
// enum domain the value codec reads, and the presentation, defaults and
// literal GUI placements the settings editor reads. Source provenance stays in
// the browser schema, bound here by its digest.
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { spawnSync } from "node:child_process";
import { validateEngineOptionSchema } from "../../web/src/settings/generated/loader.ts";
import { canonicalStringify } from "../../web/src/project/domain/canonical.ts";
import {
  ENGINE_OPTION_SCHEMA_VERSION,
  ENGINE_OPTION_SOURCE_COMMIT,
} from "../../web/src/settings/generated/types.ts";

const root = new URL("../../", import.meta.url);
const schemaPath = "web/src/settings/generated/engine-options.schema.json";
const text = readFileSync(new URL(schemaPath, root), "utf8");
const schema = validateEngineOptionSchema(JSON.parse(text));
const digest = createHash("sha256").update(text).digest("hex");

const pascal = (value) =>
  value
    .split(/[-_]/)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");
const str = (value) => JSON.stringify(value);
const char = (value) => (value === null ? "None" : `Some(${str(value)})`);
const float = (value) => {
  if (value === null) return "None";
  assert.ok(Number.isFinite(value));
  let literal = Object.is(value, -0) ? "-0" : String(value);
  literal = literal.replace("e+", "e");
  if (!/[.e]/.test(literal)) literal += ".0";
  return `Some(${literal})`;
};
const valueTypes = {
  none: "ValueType::None",
  float: "ValueType::Float",
  int: "ValueType::Int",
  string: "ValueType::String",
  "float-or-percent": "ValueType::FloatOrPercent",
  point2: "ValueType::Point2",
  point3: "ValueType::Point3",
  bool: "ValueType::Bool",
  enum: "ValueType::Enum",
};
const percent = {
  none: "Percent::None",
  percent: "Percent::Percent",
  "float-or-percent": "Percent::FloatOrPercent",
};

let rust =
  "// Generated by tools/cross-platform/generate-engine-options.mjs. Do not edit.\n" +
  "use super::{Definition, OptionType, Percent, Shape, ValueType};\n" +
  `pub const SCHEMA_VERSION: u32 = ${ENGINE_OPTION_SCHEMA_VERSION};\n` +
  `pub const SOURCE_COMMIT: &str = ${str(ENGINE_OPTION_SOURCE_COMMIT)};\n` +
  `pub const SCHEMA_SHA256: &str = ${str(digest)};\n` +
  "pub static DEFINITIONS: &[Definition] = &[\n";
for (const d of schema.definitions) {
  const s = d.storage;
  assert.ok(Object.hasOwn(valueTypes, s.valueType), s.valueType);
  rust += `Definition { id: ${str(d.id)}, key: ${str(d.key)}, owner: ${str(d.owner)}, `;
  rust += `option_type: OptionType::${pascal(s.optionType)}, value_type: ${valueTypes[s.valueType]}, `;
  rust += `shape: Shape::${pascal(s.shape)}, nullable: ${s.nullable}, percent: ${percent[s.percentSemantics]}, `;
  rust += `collection_delimiter: ${char(s.serialization.collectionDelimiter)}, `;
  rust += `component_delimiter: ${char(s.serialization.componentDelimiter)}, `;
  rust += `nil_token: ${char(s.serialization.nilToken)}, percent_suffix: ${char(s.serialization.percentSuffix)}, `;
  rust += `min: ${float(d.constraints.min.value)}, max: ${float(d.constraints.max.value)}, `;
  rust += `enum_values: &[${d.enum.values.map((v) => str(v.value)).join(", ")}], `;
  rust += `enum_labels: &[${d.enum.labels.map((v) => str(v.value)).join(", ")}] },\n`;
}
rust += "];\n";

// The editor's presentation table: labels, modes, defaults and the literal
// GUI placements the field projection reads, in definition order.
const optional = (value) =>
  value === null || value === undefined ? "None" : `Some(${str(value)})`;
const tabIndex = new Map(schema.guiLayout.tabs.map((tab, i) => [tab.id, i]));
const groupIndex = new Map(
  schema.guiLayout.groups.map((group, i) => [group.id, i]),
);
const placementsByDefinition = new Map();
schema.guiLayout.placements.forEach((placement, index) => {
  for (const id of placement.definitionBinding.definitionIds) {
    const entries = placementsByDefinition.get(id) ?? [];
    entries.push(index);
    placementsByDefinition.set(id, entries);
  }
});
const surface = (value) => `Surface::${pascal(value)}`;
const order = (value) => {
  assert.ok(Number.isSafeInteger(value) && value >= 0);
  return String(value);
};
let editor =
  "// Generated by tools/cross-platform/generate-engine-options.mjs. Do not edit.\n" +
  "use super::{Group, Mode, Placement, Presentation, Surface, Tab, Technology};\n" +
  "pub static PRESENTATION: &[Presentation] = &[\n";
for (const d of schema.definitions) {
  const p = d.presentation;
  editor += `Presentation { label: ${optional(p.label.value)}, full_label: ${optional(p.fullLabel.value)}, `;
  editor += `category: ${optional(p.category.value)}, tooltip: ${optional(p.tooltip.value)}, unit: ${optional(p.unit.value)}, `;
  editor += `mode: Mode::${pascal(d.applicability.mode.value)}, technology: Technology::${pascal(d.applicability.technology.value)}, `;
  editor += `readonly: ${p.readonly.value}, gui_type: ${str(p.guiType.value)}, `;
  editor += `aliases: &[${d.behavior.aliases.value.map(str).join(", ")}], `;
  editor += `conditional_enum: ${d.enum.valuesExtended.length > 0 || d.enum.valuesU1.length > 0}, `;
  editor += `default: ${d.default.provided ? `Some(${str(canonicalStringify(d.default.value))})` : "None"}, `;
  editor += `placements: &[${(placementsByDefinition.get(d.id) ?? []).join(", ")}] },\n`;
}
editor += "];\npub static TABS: &[Tab] = &[\n";
for (const t of schema.guiLayout.tabs)
  editor += `Tab { id: ${str(t.id)}, label: ${str(t.label)}, order: ${order(t.order)}, surface: ${surface(t.surface)} },\n`;
editor += "];\npub static GROUPS: &[Group] = &[\n";
for (const g of schema.guiLayout.groups)
  editor += `Group { id: ${str(g.id)}, label: ${str(g.label)}, order: ${order(g.order)}, surface: ${surface(g.surface)}, tab: ${tabIndex.get(g.tabId)} },\n`;
editor += "];\npub static PLACEMENTS: &[Placement] = &[\n";
for (const p of schema.guiLayout.placements)
  editor += `Placement { id: ${str(p.id)}, order: ${order(p.order)}, surface: ${surface(p.surface)}, tab: ${tabIndex.get(p.tabId)}, group: ${groupIndex.get(p.groupId)} },\n`;
editor += "];\n";
editor += `pub static SPECIAL_WIDGET_KEYS: &[&str] = &[${schema.guiLayout.unresolved.specialWidgets.map((w) => str(w.optionKey)).join(", ")}];\n`;
editor += `pub static PROJECT_CONFIG_WRITE_KEYS: &[&str] = &[${schema.guiLayout.scopeEvidence.projectConfigWrites.map((w) => str(w.optionKey)).join(", ")}];\n`;

function rustfmt(source) {
  const directory = mkdtempSync(join(tmpdir(), "orcaxr-engine-options-"));
  try {
    const path = join(directory, "options.rs");
    writeFileSync(path, source);
    const result = spawnSync(
      "rustfmt",
      ["+1.94.1", "--edition", "2024", path],
      {
        stdio: "inherit",
        timeout: 60000,
      },
    );
    assert.equal(result.status, 0, result.error?.message);
    return readFileSync(path, "utf8");
  } finally {
    rmSync(directory, { recursive: true, force: true });
  }
}
for (const [file, source] of [
  ["core/crates/orcaxr-project/src/settings/options/generated.rs", rust],
  ["core/crates/orcaxr-project/src/settings/editor/generated.rs", editor],
]) {
  const formatted = rustfmt(source);
  const target = new URL(file, root);
  if (process.argv.includes("--write")) writeFileSync(target, formatted);
  else
    assert.equal(
      readFileSync(target, "utf8"),
      formatted,
      `${file} needs regeneration`,
    );
}
console.log(
  `Engine-option tables: ${schema.definitions.length} definitions, ${schema.guiLayout.placements.length} placements from ${schemaPath} (${digest.slice(0, 12)})`,
);
