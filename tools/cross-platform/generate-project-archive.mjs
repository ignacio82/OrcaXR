// Host archive policy contract: the few budgets a host chooses for archive Open
// and Save. Every detailed ZIP/XML/model/metadata/settings/OPC/package limit
// derives from these in orcaxr_archive::policy, so WASM and JNI hosts enforce one
// policy. Generates Rust, TypeScript and Kotlin layouts with bounded codecs.
import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
const root = new URL("../../", import.meta.url);
const s = JSON.parse(readFileSync(new URL("contracts/project-archive.json", root)));
assert.deepEqual(Object.keys(s).sort(), ["version", "maxChunkBytes", "maxBudget", "options", "formats"].sort());
for (const key of ["version", "maxChunkBytes", "maxBudget"])
  assert.ok(Number.isSafeInteger(s[key]) && s[key] > 0 && s[key] <= 0xffffffff, key);
assert.equal(s.maxBudget, 0xffffffff);
assert.deepEqual(s.options, [
  "archiveBytes",
  "entries",
  "entryBytes",
  "totalBytes",
  "vertices",
  "triangles",
  "records",
  "textUnits",
  "paintNodes",
  "assets",
  "assetBytes",
  "totalAssetBytes",
  "warnings",
]);
assert.deepEqual(s.formats, ["canonical", "foreign"]);
const snake = (name) => name.replace(/[A-Z]/g, (c) => "_" + c.toLowerCase());
const index = (name) => s.options.indexOf(name);
const header = "// Generated by tools/cross-platform/generate-project-archive.mjs. Do not edit.\n";
let rust = header;
for (const [key, value] of Object.entries(s))
  if (typeof value === "number") rust += `pub const ${snake(key).toUpperCase()}: usize = ${value};\n`;
rust += `pub const OPTION_COUNT: usize = ${s.options.length};\n`;
for (const [i, key] of s.formats.entries()) rust += `pub const FORMAT_${key.toUpperCase()}: u32 = ${i};\n`;
rust += "/// Host archive budgets; every one is at least 1 and fits `MAX_BUDGET`.\n#[derive(Debug, Clone, Copy, PartialEq, Eq)]\npub struct ArchiveOptions {\n";
for (const key of s.options) rust += `    pub ${snake(key)}: usize,\n`;
rust += `}
/// Exact version, positive integral budgets, and per-item caps no larger than
/// their totals. Anything else is refused before any archive work starts.
pub fn decode_options(version: f64, input: &[f64]) -> Option<ArchiveOptions> {
    if version != VERSION as f64
        || input.len() != OPTION_COUNT
        || input
            .iter()
            .any(|v| !v.is_finite() || v.fract() != 0.0 || *v < 1.0 || *v > MAX_BUDGET as f64)
    {
        return None;
    }
    let result = ArchiveOptions {
`;
for (const [i, key] of s.options.entries()) rust += `        ${snake(key)}: input[${i}] as usize,\n`;
rust += `    };
    if result.entry_bytes > result.total_bytes || result.asset_bytes > result.total_asset_bytes {
        return None;
    }
    Some(result)
}
`;
let ts = header + `export const PROJECT_ARCHIVE = ${JSON.stringify(s, null, 2)} as const;\nexport interface ProjectArchiveOptions {\n`;
for (const key of s.options) ts += `  readonly ${key}: number;\n`;
ts += `}
export function encodeProjectArchiveOptions(value: ProjectArchiveOptions): Float64Array {
  const keys = Reflect.ownKeys(value);
  if (keys.length !== PROJECT_ARCHIVE.options.length || keys.some(k => typeof k !== 'string' || !(PROJECT_ARCHIVE.options as readonly string[]).includes(k))) throw new Error('Invalid project archive options');
  const result = PROJECT_ARCHIVE.options.map(key => {
    const field = Object.getOwnPropertyDescriptor(value, key);
    const number: unknown = field?.value;
    if (!field || !('value' in field) || typeof number !== 'number' || !Number.isInteger(number) || number < 1 || number > PROJECT_ARCHIVE.maxBudget) throw new Error('Invalid project archive options');
    return number;
  });
  if (result[${index("entryBytes")}]! > result[${index("totalBytes")}]! || result[${index("assetBytes")}]! > result[${index("totalAssetBytes")}]!) throw new Error('Invalid project archive options');
  return new Float64Array(result);
}
`;
let kotlin = header + "package dev.orcaxr.core\n\nobject ProjectArchive {\n";
for (const [key, value] of Object.entries(s))
  if (typeof value === "number") kotlin += `    const val ${snake(key).toUpperCase()} = ${value}${key === "maxBudget" ? "L" : ""}\n`;
kotlin += `    const val OPTION_COUNT = ${s.options.length}\n`;
for (const [i, key] of s.formats.entries()) kotlin += `    const val FORMAT_${key.toUpperCase()} = ${i}\n`;
kotlin += "}\n\ndata class ProjectArchiveOptions(\n";
for (const key of s.options) kotlin += `    val ${key}: Long,\n`;
kotlin += `) {\n    fun encode(): DoubleArray {\n        val values = longArrayOf(${s.options.join(", ")})\n        require(values.all { it in 1..ProjectArchive.MAX_BUDGET } && entryBytes <= totalBytes && assetBytes <= totalAssetBytes) { "Invalid project archive options" }\n        return values.map { it.toDouble() }.toDoubleArray()\n    }\n}\n`;
for (const [path, content] of [
  ["core/crates/orcaxr-archive/src/archive_layout.rs", rust],
  ["contracts/generated/project-archive.ts", ts],
  ["android/core-bridge/src/main/java/dev/orcaxr/core/ProjectArchive.kt", kotlin],
]) {
  const url = new URL(path, root);
  if (process.argv.includes("--write")) writeFileSync(url, content);
  else assert.equal(readFileSync(url, "utf8"), content, `${path} requires regeneration`);
}
console.log("Verified shared project archive policy options and formats");
