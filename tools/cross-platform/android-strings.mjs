/** A BCP-47 tag as an Android resource qualifier: `de`, `pt-rBR`, `b+zh+Hans`. */
function qualifier(tag) {
  const parts = tag.split("-");
  if (parts.length === 1) return parts[0];
  if (parts.length === 2 && /^[A-Z]{2}$/.test(parts[1]))
    return `${parts[0]}-r${parts[1]}`;
  return `b+${parts.join("+")}`;
}

function renderResources(locale, entries) {
  let xml = `<?xml version="1.0" encoding="utf-8"?>\n<!-- ${MARK} from ${CATALOGUES}/${locale}.json through ${CONTRACT}. Do not edit. -->\n<resources>\n`;
  for (const [name, converted] of entries) {
    if (converted.kind === "string") {
      const unformatted =
        !converted.formatted && converted.text.includes("%")
          ? ' formatted="false"'
          : "";
      xml += `    <string name="${name}"${unformatted}>${androidEscape(converted.text)}</string>\n`;
    } else {
      xml += `    <plurals name="${name}">\n`;
      for (const key of CATEGORIES)
        if (key in converted.items)
          xml += `        <item quantity="${key}">${androidEscape(converted.items[key])}</item>\n`;
      xml += "    </plurals>\n";
    }
  }
  return `${xml}</resources>\n`;
}

function renderLocaleConfig(languages) {
  return (
    `<?xml version="1.0" encoding="utf-8"?>\n<!-- ${MARK}: the browser's languages that carry any of the app's words. Do not edit. -->\n` +
    `<locale-config xmlns:android="http://schemas.android.com/apk/res/android">\n` +
    languages.map((tag) => `    <locale android:name="${tag}" />\n`).join("") +
    "</locale-config>\n"
  );
}

/** Files under the resources this generator wrote before, by their mark. */
function generatedFiles() {
  const out = [];
  for (const entry of readdirSync(at(RES), { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    for (const file of readdirSync(at(`${RES}/${entry.name}`))) {
      const path = `${RES}/${entry.name}/${file}`;
      if (file.endsWith(".xml") && read(path).includes(MARK)) out.push(path);
    }
  }
  return out.sort();
}

function walk(directory) {
  if (!existsSync(at(directory))) return [];
  const out = [];
  for (const entry of readdirSync(at(directory), { withFileTypes: true })) {
    const path = `${directory}/${entry.name}`;
    if (entry.isDirectory()) out.push(...walk(path));
    else out.push(path);
  }
  return out.sort();
}
