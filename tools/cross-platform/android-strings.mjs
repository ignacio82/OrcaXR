// The Android app's words, kept to the browser's: checks the maintained mapping
// in contracts/android-strings.json and generates the app's localized string
// resources from the browser's message catalogues (web/public/l10n). Check mode
// by default; `--write` regenerates.
//
// Every string resource the app defines (android/app/src/main/res/values) is
// either mapped to the browser message carrying the same English — checked to
// say exactly what the browser's source says, so the copies cannot drift — or
// listed as English only: no browser message carries it, and it stays English
// in every language, as a message the browser's catalogue lacks does. An
// English-only resource whose words a browser message now carries fails until
// it is mapped or declined with a reason; so does a Kotlin literal of the app
// that carries a browser message's words, until the contract records it.
//
// Each mapped message is converted from the browser's ICU syntax — parsed by
// the browser's own `icu.ts`, so nothing here has a second idea of the grammar —
// to an Android format string: every argument becomes `%N$s` in the contract's
// declared order, formatted by the host as the browser formats it (text as is,
// numbers as `{n, number}`), and one plural becomes `<plurals>` with the text
// around it repeated in each form and its categories limited to the locale's.
// What Android cannot express exactly — select, exact `=N` and offset plurals,
// ordinals, a second or nested plural, unit/date/time and styled numbers, one
// argument used both as text and as a number — is refused, never approximated:
// a refused translation falls back to English, a refused English fails. Each
// conversion is then rendered against the browser's `formatMessage` for sample
// values, Android's selection simulated with the same CLDR rules, and must agree.
//
// Outputs: values-<qualifier>/strings.xml for each browser locale that
// translates any mapped message (BCP-47 → Android qualifiers, `b+` where a
// script is named) and xml/locales_config.xml, the languages the app offers.
