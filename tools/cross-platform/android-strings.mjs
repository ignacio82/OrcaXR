// ---- ICU to Android --------------------------------------------------------

/**
 * One browser message as an Android resource in [locale]: `{kind: "string",
 * text}` or `{kind: "plurals", items}`, with `arguments` (the declared order)
 * and each argument's `kinds` ("text" or "number"). Throws a Refusal for what
 * Android cannot say exactly.
 */
function toAndroid(message, locale, names) {
  let nodes;
  try {
    nodes = parseMessage(message);
  } catch (error) {
    refuse(`it does not parse (${error.message})`);
  }
  if (message.includes("\u0001")) refuse("it holds U+0001");
  const kinds = new Map();
  const use = (name, kind) => {
    const position = names.indexOf(name);
    if (position < 0)
      refuse(
        `{${name}} is not among the declared arguments [${names.join(", ")}]`,
      );
    if (kinds.has(name) && kinds.get(name) !== kind)
      refuse(
        `{${name}} is both text and a number, which one Android argument cannot be`,
      );
    kinds.set(name, kind);
    return `%${position + 1}$s`;
  };
  const plurals = nodes.filter((node) => node.kind === "plural");
  if (plurals.length > 1) refuse("it has more than one plural");
  const flat = (list, pound) =>
    list
      .map((node) => {
        switch (node.kind) {
          case "text":
            return node.value;
          case "pound":
            return pound;
          case "argument":
            return use(node.name, "text");
          case "number":
            if (node.style)
              refuse(`{${node.name}, number, ${node.style}} has a style`);
            return use(node.name, "number");
          case "plural":
            return refuse("a plural is nested");
          case "select":
            return refuse("select has no Android resource form");
          default:
            return refuse(
              `{${node.name}, ${node.kind}} has no Android argument form`,
            );
        }
      })
      .join("");
  // Each piece of text is marked so its `%` can be escaped once arguments are known.
  const TEXT = "\u0001";
  const mark = (list) =>
    list.map((node) =>
      node.kind === "text"
        ? { kind: "text", value: TEXT + node.value + TEXT }
        : node,
    );
  let result;
  if (plurals.length === 0) {
    result = { kind: "string", text: flat(mark(nodes)) };
  } else {
    const [plural] = plurals;
    if (plural.ordinal) refuse("selectordinal: Android plurals are cardinal");
    if (plural.offset !== 0) refuse("a plural offset has no Android form");
    if (!plural.branches.has("other")) refuse("the plural has no other form");
    const pound = use(plural.name, "number");
    const index = nodes.indexOf(plural);
    const prefix = flat(mark(nodes.slice(0, index)));
    const suffix = flat(mark(nodes.slice(index + 1)));
    const used = new Intl.PluralRules(locale).resolvedOptions()
      .pluralCategories;
    const items = {};
    for (const [key, branch] of plural.branches) {
      if (key.startsWith("="))
        refuse(`the exact form ${key} has no Android quantity`);
      if (!CATEGORIES.includes(key)) refuse(`${key} is no plural category`);
      // A category the language never selects is never shown, in either.
      if (!used.includes(key)) continue;
      items[key] = prefix + flat(mark(branch), pound) + suffix;
    }
    result = { kind: "plurals", items, quantity: plural.name };
  }
  // An Android format string doubles a literal `%`; one without arguments is not formatted.
  const formatted = kinds.size > 0;
  const finish = (text) =>
    text.replace(/\u0001([^\u0001]*)\u0001/g, (_, value) =>
      formatted ? value.replaceAll("%", "%%") : value,
    );
  if (result.kind === "string") result.text = finish(result.text);
  else
    for (const key of Object.keys(result.items))
      result.items[key] = finish(result.items[key]);
  result.arguments = names;
  result.kinds = kinds;
  result.formatted = formatted;
  for (const name of names)
    if (!kinds.has(name) && locale === REFERENCE_LOCALE)
      refuse(`the declared argument ${name} is not in the message`);
  // Characters a resource cannot hold refuse here, not when the file is written.
  for (const text of result.kind === "string"
    ? [result.text]
    : Object.values(result.items))
    androidEscape(text);
  return result;
}

/**
 * Render [converted] as Android would for sample values — arguments formatted
 * as the browser formats them, the plural form chosen by the same CLDR rules —
 * and require the browser's own rendering of [message].
 */
function verify(message, locale, converted) {
  const samples = {
    text: ["plate.gcode", "Part #2", "50% {x} 'q' \"d\" \\ @?", "%1$s"],
  };
  const numbers = [
    0, 1, 2, 3, 4, 5, 6, 7, 11, 12, 15, 21, 22, 25, 100, 101, 102, 111, 1000,
    1001, 21000, 1000000,
  ];
  const fractions = [0.5, 1.25, 1234.567];
  const choices = converted.arguments.map((name) => {
    const kind = converted.kinds.get(name);
    if (kind === "text") return samples.text;
    return name === converted.quantity ? numbers : [...numbers, ...fractions];
  });
  const total = choices.reduce((product, list) => product * list.length, 1);
  const assignments = [];
  if (total <= 2000) {
    const build = (index, current) => {
      if (index === choices.length) assignments.push(current);
      else
        for (const value of choices[index])
          build(index + 1, [...current, value]);
    };
    build(0, []);
  } else {
    // One argument varying at a time, the others at their first sample.
    choices.forEach((list, index) =>
      list.forEach((value) =>
        assignments.push(
          choices.map((other, at) => (at === index ? value : other[0])),
        ),
      ),
    );
  }
  const number = (value) =>
    formatMessage("{v, number}", { locale, values: { v: value } });
  for (const assignment of assignments) {
    const values = Object.fromEntries(
      converted.arguments.map((name, index) => [name, assignment[index]]),
    );
    const failures = [];
    const browser = formatMessage(message, {
      locale,
      values,
      onProblem: (found) => failures.push(found.message),
    });
    if (failures.length > 0)
      refuse(`the browser reports ${failures.join("; ")}`);
    const args = converted.arguments.map((name) =>
      converted.kinds.get(name) === "number"
        ? number(values[name])
        : String(values[name]),
    );
    const format =
      converted.kind === "string"
        ? converted.text
        : (converted.items[
            new Intl.PluralRules(locale).select(values[converted.quantity])
          ] ?? converted.items.other);
    const android = converted.formatted
      ? format.replace(/%(?:(\d+)\$s|%)/g, (_, position) =>
          position ? args[Number(position) - 1] : "%",
        )
      : format;
    if (android !== browser)
      refuse(
        `for ${JSON.stringify(values)} Android would show ${JSON.stringify(android)}, the browser ${JSON.stringify(browser)}`,
      );
  }
}

/** A resource's or conversion's kind and text, for comparing and for messages. */
function describe(resource) {
  if (resource.kind === "string") return JSON.stringify(resource.text);
  return `<plurals> ${JSON.stringify(
    Object.fromEntries(
      CATEGORIES.filter((key) => key in resource.items).map((key) => [
        key,
        resource.items[key],
      ]),
    ),
  )}`;
}

/** A message's words with each simple argument as U+0000, or undefined when it is more than that. */
function normalizedMessage(message) {
  let nodes;
  try {
    nodes = parseMessage(message);
  } catch {
    return undefined;
  }
  if (!nodes.every((node) => node.kind === "text" || node.kind === "argument"))
    return undefined;
  return nodes
    .map((node) => (node.kind === "text" ? node.value : "\u0000"))
    .join("");
}

/** A string resource's words with each format argument as U+0000. */
function normalizedResource(resource) {
  if (resource?.kind !== "string") return undefined;
  if (!resource.formatted) return resource.text;
  return resource.text.replace(
    /%(?:\d+\$)?[-#+ 0,(]*\d*(?:\.\d+)?[a-zA-Z]|%%/g,
    (match) => (match === "%%" ? "%" : "\u0000"),
  );
}

// ---- Kotlin -------------------------------------------------------------

/** A message as Kotlin template parts, its arguments as the contract's expressions. */
function kotlinParts(message, expressions) {
  let nodes;
  try {
    nodes = parseMessage(message);
  } catch {
    return undefined;
  }
  if (!nodes.every((node) => node.kind === "text" || node.kind === "argument"))
    return undefined;
  return nodes.map((node) => {
    if (node.kind === "text") return { text: node.value };
    const expression = expressions[node.name];
    if (expression === undefined) return { expression: `{${node.name}}` };
    return { expression };
  });
}

function sameParts(literal, expected) {
  const merged = (parts) => {
    const out = [];
    for (const part of parts) {
      const last = out.at(-1);
      if (part.text !== undefined && last?.text !== undefined)
        last.text += part.text;
      else out.push({ ...part });
    }
    return out.filter((part) => part.text !== "");
  };
  const a = merged(literal);
  const b = merged(expected);
  return (
    a.length === b.length &&
    a.every((part, index) =>
      part.text !== undefined
        ? part.text === b[index].text
        : b[index].expression !== undefined &&
          part.expression.replace(/\s+/g, " ") ===
            b[index].expression.replace(/\s+/g, " "),
    )
  );
}

function partsWords(parts) {
  return parts
    .map((part) => (part.text !== undefined ? part.text : "\u0000"))
    .join("");
}

/**
 * Kotlin's string literals, each as text and template parts, with the line it
 * starts on and its order there. Comments and character literals are skipped;
 * literals inside a template's expression are literals too.
 */
function lexKotlin(source) {
  const found = [];
  let i = 0;
  const lineStarts = [0];
  for (let at = 0; at < source.length; at += 1)
    if (source[at] === "\n") lineStarts.push(at + 1);
  const lineOf = (index) => {
    let low = 0;
    let high = lineStarts.length - 1;
    while (low < high) {
      const middle = (low + high + 1) >> 1;
      if (lineStarts[middle] <= index) low = middle;
      else high = middle - 1;
    }
    return low + 1;
  };
  const perLine = new Map();
  const code = (insideTemplate) => {
    let depth = 0;
    while (i < source.length) {
      const c = source[i];
      if (c === "/" && source[i + 1] === "/") {
        while (i < source.length && source[i] !== "\n") i += 1;
      } else if (c === "/" && source[i + 1] === "*") {
        let nesting = 0;
        do {
          if (source.startsWith("/*", i)) {
            nesting += 1;
            i += 2;
          } else if (source.startsWith("*/", i)) {
            nesting -= 1;
            i += 2;
          } else i += 1;
        } while (nesting > 0 && i < source.length);
      } else if (c === '"') {
        string();
      } else if (c === "'") {
        // A character literal: '"' must not open a string.
        i += source[i + 1] === "\\" ? 3 : 2;
        while (i < source.length && source[i] !== "'") i += 1;
        i += 1;
      } else {
        if (c === "{") depth += 1;
        if (c === "}") {
          if (insideTemplate && depth === 0) return;
          depth -= 1;
        }
        i += 1;
      }
    }
  };
  const string = () => {
    const start = i;
    const raw = source.startsWith('"""', i);
    i += raw ? 3 : 1;
    const parts = [];
    let text = "";
    const flush = () => {
      if (text) parts.push({ text });
      text = "";
    };
    for (;;) {
      assert.ok(
        i < source.length,
        `unterminated string at line ${lineOf(start)}`,
      );
      if (raw && source.startsWith('"""', i) && !source.startsWith('""""', i)) {
        i += 3;
        break;
      }
      if (!raw && source[i] === '"') {
        i += 1;
        break;
      }
      const c = source[i];
      if (!raw && c === "\\") {
        const next = source[i + 1];
        if (next === "u") {
          text += String.fromCharCode(
            Number.parseInt(source.slice(i + 2, i + 6), 16),
          );
          i += 6;
        } else {
          text += { t: "\t", b: "\b", n: "\n", r: "\r" }[next] ?? next;
          i += 2;
        }
        continue;
      }
      if (c === "$" && source[i + 1] === "{") {
        flush();
        i += 2;
        const from = i;
        code(true);
        parts.push({ expression: source.slice(from, i).trim() });
        i += 1;
        continue;
      }
      if (c === "$" && /[A-Za-z_]/.test(source[i + 1] ?? "")) {
        flush();
        i += 1;
        const from = i;
        while (/[A-Za-z0-9_]/.test(source[i] ?? "")) i += 1;
        parts.push({ expression: source.slice(from, i) });
        continue;
      }
      assert.ok(
        raw || c !== "\n",
        `unterminated string at line ${lineOf(start)}`,
      );
      text += c;
      i += 1;
    }
    flush();
    const line = lineOf(start);
    const index = perLine.get(line) ?? 0;
    perLine.set(line, index + 1);
    found.push({ line, index, parts });
  };
  code(false);
  return found;
}

// ---- Android resource files ---------------------------------------------

/**
 * The `<string>` and `<plurals>` resources of every XML file in [directory],
 * as Android reads their text (XML first, then aapt2's quoting, escapes and
 * whitespace). Markup inside a string is refused: nothing here writes any.
 */
function readResources(directory) {
  const out = new Map();
  for (const file of readdirSync(at(directory))
    .filter((name) => name.endsWith(".xml"))
    .sort()) {
    const document = parseXml(read(`${directory}/${file}`));
    assert.equal(
      document.name,
      "resources",
      `${directory}/${file} is no resources file`,
    );
    for (const element of document.children) {
      if (typeof element === "string") continue;
      const name = element.attributes.name;
      if (element.name === "string") {
        const text = androidText(textOf(element, `${file}: ${name}`));
        out.set(name, {
          kind: "string",
          text,
          translatable: element.attributes.translatable !== "false",
          formatted:
            element.attributes.formatted !== "false" && text.includes("%"),
        });
      } else if (element.name === "plurals") {
        const items = {};
        for (const item of element.children) {
          if (typeof item === "string") continue;
          assert.equal(item.name, "item", `${name} holds a ${item.name}`);
          items[item.attributes.quantity] = androidText(
            textOf(item, `${file}: ${name}`),
          );
        }
        out.set(name, {
          kind: "plurals",
          items,
          translatable: element.attributes.translatable !== "false",
          formatted: true,
        });
      } else if (["string-array", "item"].includes(element.name)) {
        problem(
          `${file}: ${element.name} ${name} is not supported by ${GENERATOR}`,
        );
      }
    }
  }
  return out;
}

function textOf(element, where) {
  for (const child of element.children)
    if (typeof child !== "string")
      problem(`${where} holds markup, which is not carried`);
  return element.children.filter((child) => typeof child === "string").join("");
}

/** aapt2's reading of a resource string: quotes, escapes, collapsed and trimmed whitespace. */
function androidText(xmlText) {
  const chars = []; // [char, collapsible]
  let quoted = false;
  for (let index = 0; index < xmlText.length; index += 1) {
    const c = xmlText[index];
    if (c === '"') {
      quoted = !quoted;
    } else if (c === "\\") {
      const next = xmlText[index + 1];
      index += 1;
      if (next === "u") {
        chars.push([
          String.fromCharCode(
            Number.parseInt(xmlText.slice(index + 1, index + 5), 16),
          ),
          false,
        ]);
        index += 4;
      } else chars.push([{ t: "\t", n: "\n" }[next] ?? next, false]);
    } else if (/[ \t\n\r\f\v]/.test(c) && !quoted) {
      // aapt2's isspace: ASCII only, so a no-break space stays.
      if (!(chars.length > 0 && chars.at(-1)[1])) chars.push([" ", true]);
    } else {
      chars.push([c, false]);
    }
  }
  while (chars.length > 0 && chars[0][1]) chars.shift();
  while (chars.length > 0 && chars.at(-1)[1]) chars.pop();
  return chars.map(([c]) => c).join("");
}

/** A resource string as aapt2 reads it back: every character Android would not take as itself escaped. */
function androidEscape(text) {
  const chars = [...text];
  let out = "";
  chars.forEach((c, index) => {
    const code = c.codePointAt(0);
    if (c === "\\") out += "\\\\";
    else if (c === "'") out += "\\'";
    else if (c === '"') out += '\\"';
    else if (c === "\n") out += "\\n";
    else if (c === "\t") out += "\\t";
    else if ((c === "@" || c === "?") && index === 0) out += `\\${c}`;
    else if (
      c === " " &&
      (index === 0 || index === chars.length - 1 || chars[index - 1] === " ")
    )
      out += "\\u0020";
    else if (c === "&") out += "&amp;";
    else if (c === "<") out += "&lt;";
    else if (c === ">") out += "&gt;";
    else if (
      code < 0x20 ||
      code === 0x7f ||
      (code >= 0xd800 && code <= 0xdfff) ||
      code === 0xfffe ||
      code === 0xffff
    )
      refuse(
        `U+${code.toString(16).toUpperCase().padStart(4, "0")} cannot be written in a resource`,
      );
    else out += c;
  });
  assert.equal(androidText(decodeEntities(out)), text, "escaping round-trips");
  return out;
}

/** A minimal XML reader for resource files: elements, attributes, text, comments. */
function parseXml(source) {
  let i = 0;
  const skipMisc = () => {
    for (;;) {
      while (/\s/.test(source[i] ?? "")) i += 1;
      if (source.startsWith("<?", i)) i = source.indexOf("?>", i) + 2;
      else if (source.startsWith("<!--", i)) i = source.indexOf("-->", i) + 3;
      else return;
    }
  };
  const element = () => {
    assert.equal(source[i], "<");
    i += 1;
    const name = source.slice(i).match(/^[\w:.-]+/)[0];
    i += name.length;
    const attributes = {};
    for (;;) {
      while (/\s/.test(source[i])) i += 1;
      if (source.startsWith("/>", i)) {
        i += 2;
        return { name, attributes, children: [] };
      }
      if (source[i] === ">") {
        i += 1;
        break;
      }
      const attribute = source
        .slice(i)
        .match(/^([\w:.-]+)\s*=\s*("([^"]*)"|'([^']*)')/);
      assert.ok(attribute, `malformed attribute in <${name}>`);
      attributes[attribute[1].replace(/^.*:/, "")] = decodeEntities(
        attribute[3] ?? attribute[4],
      );
      i += attribute[0].length;
    }
    const children = [];
    for (;;) {
      if (source.startsWith("</", i)) {
        const close = source.indexOf(">", i);
        assert.equal(
          source.slice(i + 2, close).trim(),
          name,
          `</${name}> expected`,
        );
        i = close + 1;
        return { name, attributes, children };
      }
      if (source.startsWith("<!--", i)) i = source.indexOf("-->", i) + 3;
      else if (source.startsWith("<![CDATA[", i)) {
        const end = source.indexOf("]]>", i);
        children.push(source.slice(i + 9, end));
        i = end + 3;
      } else if (source[i] === "<") children.push(element());
      else {
        const end = source.indexOf("<", i);
        children.push(decodeEntities(source.slice(i, end)));
        i = end;
      }
    }
  };
  skipMisc();
  return element();
}

function decodeEntities(text) {
  return text.replace(
    /&(#x[0-9a-fA-F]+|#\d+|amp|lt|gt|quot|apos);/g,
    (_, entity) => {
      if (entity[0] === "#")
        return String.fromCodePoint(
          entity[1] === "x"
            ? Number.parseInt(entity.slice(2), 16)
            : Number.parseInt(entity.slice(1), 10),
        );
      return { amp: "&", lt: "<", gt: ">", quot: '"', apos: "'" }[entity];
    },
  );
}

