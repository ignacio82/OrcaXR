import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
const root = new URL("../../", import.meta.url);
const s = JSON.parse(
  readFileSync(new URL("contracts/project-host.json", root)),
);
assert.deepEqual(
  Object.keys(s).sort(),
  [
    "version",
    "maxChunkBytes",
    "maxTextChunkUnits",
    "maxSupportedDepth",
    "maxSelectionRefs",
    "maxSelectionTextUnits",
    "maxBudget",
    "options",
    "effects",
    "selectionKinds",
  ].sort(),
);
for (const key of [
  "version",
  "maxChunkBytes",
  "maxTextChunkUnits",
  "maxSupportedDepth",
  "maxSelectionRefs",
  "maxSelectionTextUnits",
  "maxBudget",
]) {
  const value = s[key];
  assert.ok(
    typeof value === "number" &&
      Number.isSafeInteger(value) &&
      value > 0 &&
      value <= 0xffffffff,
    key,
  );
}
assert.equal(s.maxBudget, 0xffffffff);
assert.ok(s.maxSupportedDepth <= 128);
assert.deepEqual(s.options, [
  "documentBytes",
  "documentNodes",
  "documentTextUnits",
  "numberBytes",
  "depth",
  "assets",
  "assetBytes",
  "totalAssetBytes",
  "historyEntries",
  "historyBytes",
]);
assert.deepEqual(s.effects, ["project", "selection", "history"]);
assert.deepEqual(s.selectionKinds, [
  "project",
  "plate",
  "object",
  "volume",
  "instance",
  "layer-range",
  "filament",
]);
const snake = (name) => name.replace(/[A-Z]/g, (c) => "_" + c.toLowerCase());
const header =
  "// Generated by tools/cross-platform/generate-project-host.mjs. Do not edit.\n";
let rust = header;
for (const [key, value] of Object.entries(s))
  if (typeof value === "number")
    rust += `pub const ${snake(key).toUpperCase()}: usize = ${value};\n`;
rust += "#[derive(Debug, Clone, Copy)]\npub struct HostOptions {\n";
for (const key of s.options) rust += `    pub ${snake(key)}: usize,\n`;
rust += `}
pub fn decode_options(version: f64, input: &[f64]) -> Option<HostOptions> {
    if version != VERSION as f64
        || input.len() != ${s.options.length}
        || input
            .iter()
            .any(|v| !v.is_finite() || v.fract() != 0.0 || *v < 0.0 || *v > MAX_BUDGET as f64)
    {
        return None;
    }
    let result = HostOptions {
`;
for (const [i, key] of s.options.entries())
  rust += `        ${snake(key)}: input[${i}] as usize,\n`;
rust += `    };
    if result.depth > MAX_SUPPORTED_DEPTH || result.number_bytes == 0 {
        return None;
    }
    Some(result)
}
`;
for (const [i, key] of s.effects.entries())
  rust += `pub const EFFECT_${key.toUpperCase()}: u32 = ${i};\n`;
for (const [i, key] of s.selectionKinds.entries())
  rust += `pub const SELECT_${key.replaceAll("-", "_").toUpperCase()}: u32 = ${i};\n`;
let ts =
  header +
  `export const PROJECT_HOST = ${JSON.stringify(s, null, 2)} as const;\nexport interface ProjectHostOptions {\n`;
for (const key of s.options) ts += `  readonly ${key}: number;\n`;
ts += `}
export function encodeProjectHostOptions(value: ProjectHostOptions): Float64Array {
  const keys = Reflect.ownKeys(value);
  if (keys.length !== PROJECT_HOST.options.length || keys.some(k => typeof k !== 'string' || !(PROJECT_HOST.options as readonly string[]).includes(k))) throw new Error('Invalid project host options');
  const result = PROJECT_HOST.options.map(key => {
    const field = Object.getOwnPropertyDescriptor(value, key);
    const number: unknown = field?.value;
    if (!field || !('value' in field) || typeof number !== 'number' || !Number.isInteger(number) || number < 0 || number > PROJECT_HOST.maxBudget) throw new Error('Invalid project host options');
    return number;
  });
  if (result[4]! > PROJECT_HOST.maxSupportedDepth || result[3] === 0) throw new Error('Invalid project host options');
  return new Float64Array(result);
}
`;
let kotlin = header + "package dev.orcaxr.core\n\nobject ProjectHost {\n";
for (const [key, value] of Object.entries(s))
  if (typeof value === "number")
    kotlin += `    const val ${snake(key).toUpperCase()} = ${value}${key === "maxBudget" ? "L" : ""}\n`;
for (const [i, key] of s.effects.entries())
  kotlin += `    const val EFFECT_${key.toUpperCase()} = ${i}\n`;
for (const [i, key] of s.selectionKinds.entries())
  kotlin += `    const val SELECT_${key.replaceAll("-", "_").toUpperCase()} = ${i}\n`;
kotlin += "}\n\ndata class ProjectHostOptions(\n";
for (const key of s.options) kotlin += `    val ${key}: Long,\n`;
kotlin += `) {\n    fun encode(): DoubleArray {\n        val values = longArrayOf(${s.options.join(", ")})\n        require(values.all { it in 0..ProjectHost.MAX_BUDGET } && depth <= ProjectHost.MAX_SUPPORTED_DEPTH && numberBytes > 0) { "Invalid project host options" }\n        return values.map { it.toDouble() }.toDoubleArray()\n    }\n}\n`;
for (const [path, content] of [
  ["core/crates/orcaxr-project/src/host_layout.rs", rust],
  ["contracts/generated/project-host.ts", ts],
  ["android/core-bridge/src/main/java/dev/orcaxr/core/ProjectHost.kt", kotlin],
]) {
  const url = new URL(path, root);
  if (process.argv.includes("--write")) writeFileSync(url, content);
  else
    assert.equal(
      readFileSync(url, "utf8"),
      content,
      `${path} requires regeneration`,
    );
}
console.log("Verified shared project host limits, options and effect kinds");
