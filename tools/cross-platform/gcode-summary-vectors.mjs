/** The order the engine writes an artifact's end (GCode.cpp): totals, then the full config. */
function orcaTrailer({
  lengths,
  volumes,
  weights,
  total,
  cost,
  changes,
  layers,
  time,
  first,
  colours,
  types,
  config = 0,
}) {
  const lines = ["; EXECUTABLE_BLOCK_END", ""];
  if (lengths) lines.push(`; filament used [mm] = ${lengths}`);
  if (volumes) lines.push(`; filament used [cm3] = ${volumes}`);
  if (weights) lines.push(`; filament used [g] = ${weights}`);
  if (total !== undefined) lines.push(`; total filament used [g] = ${total}`);
  if (cost !== undefined) lines.push(`; total filament cost = ${cost}`);
  if (changes !== undefined) lines.push(`; total filament change = ${changes}`);
  if (layers !== undefined) lines.push(`; total layers count = ${layers}`);
  if (time !== undefined)
    lines.push(`; estimated printing time (normal mode) = ${time}`);
  if (first !== undefined)
    lines.push(
      `; estimated first layer printing time (normal mode) = ${first}`,
    );
  lines.push("", "; CONFIG_BLOCK_START");
  for (let n = 0; n < config; n += 1)
    lines.push(`; setting_${n} = ${"value".repeat(1 + (n % 7))}`);
  if (colours !== undefined) lines.push(`; filament_colour = ${colours}`);
  if (types !== undefined) lines.push(`; filament_type = ${types}`);
  lines.push("; CONFIG_BLOCK_END", "", "");
  return lines.join("\n");
}

