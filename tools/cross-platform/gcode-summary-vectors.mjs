const text = (value) => {
  assert.ok(
    value.isWellFormed(),
    "text parts are well-formed; raw bytes go in byte parts",
  );
  return { text: value };
};
const raw = (...bytes) => ({ bytes });
const repeat = (value, times) => ({ repeat: value, times });
const repeatBytes = (bytes, times) => ({ repeatBytes: bytes, times });
const bytesOf = (parts) =>
  Buffer.concat(
    parts.map((part) =>
      part.text !== undefined
        ? Buffer.from(part.text, "utf8")
        : part.bytes !== undefined
          ? Buffer.from(part.bytes)
          : part.repeatBytes !== undefined
            ? Buffer.concat(
                Array.from({ length: part.times }, () =>
                  Buffer.from(part.repeatBytes),
                ),
              )
            : Buffer.from(part.repeat.repeat(part.times), "utf8"),
    ),
  );
const number = (value) => (Object.is(value, -0) ? "-0" : String(value));

