function summaryJson(summary) {
  const out = { empty: summary.empty, perTool: [] };
  for (const tool of summary.perTool) {
    const entry = { toolIndex: tool.toolIndex };
    for (const key of ["lengthMm", "volumeCm3", "weightG"])
      if (tool[key] !== undefined) entry[key] = number(tool[key]);
    for (const key of ["colorHex", "material"])
      if (tool[key] !== undefined) entry[key] = tool[key];
    out.perTool.push(entry);
  }
  for (const key of [
    "totalWeightG",
    "totalCost",
    "toolChanges",
    "layerCount",
    "estimatedSeconds",
    "firstLayerSeconds",
  ]) {
    if (summary[key] !== undefined) out[key] = number(summary[key]);
  }
  return out;
}

const corpus = cases.map(({ name, parts }) => {
  const decoded = new TextDecoder("utf-8").decode(bytesOf(parts));
  const summary = summarizeGcodeArtifact(decoded);
  const description = describeArtifactSummary(summary);
  return { name, parts, summary: summaryJson(summary), description };
});

