// G-code artifact summary references from the production browser
// (`web/src/slicer/GcodeArtifactSummary.ts`): the totals the engine wrote into
// a finished artifact, read from the file as the browser reads it (bytes
// decoded by `TextDecoder`), and the preview panel's wording of them
// (`describeArtifactSummary`), plus `formatArtifactDuration` over awkward
// numbers. Inputs are parts — text, raw bytes or repeated text — so large
// trailer-boundary cases stay small. Numbers are written as JavaScript spells
// them (`String(n)`, with `-0` kept). Replayed by Rust (`orcaxr_gcode::artifact`).
