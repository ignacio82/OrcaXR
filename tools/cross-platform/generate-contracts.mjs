import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import assert from 'node:assert/strict';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const schema = JSON.parse(readFileSync(resolve(root, 'contracts/core-protocol.json'), 'utf8'));
const write = process.argv.includes('--write');
assert.equal(schema.type, 'object');
assert.equal(schema.additionalProperties, false);
assert.deepEqual(Object.keys(schema).sort(), ['$schema', '$id', 'title', 'type', 'additionalProperties', 'required', 'properties', 'x-orcaxr'].sort());
assert.deepEqual(schema.required, Object.keys(schema.properties));
assert.deepEqual(schema.required, ['protocolVersion', 'requestId', 'operation', 'input']);
assert.deepEqual(schema.properties.input, {type: 'string'});
assert.deepEqual(schema.properties.operation, {const: 'canonicalize'});
assert.deepEqual(Object.keys(schema.properties.protocolVersion), ['const']);
assert.deepEqual(Object.keys(schema['x-orcaxr']).sort(), ['coreAbiVersion', 'canonicalEncodingVersion', 'maxRequestBytes', 'maxInputBytes', 'maxOutputBytes'].sort());
const snake = (name) => name.replace(/[A-Z]/g, (value) => `_${value.toLowerCase()}`);
const constants = { protocolVersion: schema.properties.protocolVersion.const, ...schema['x-orcaxr'] };
const keys = Object.keys(schema.properties);
for (const value of Object.values(constants)) assert.ok(Number.isSafeInteger(value) && value > 0 && value <= 0x7fffffff);
for (const definition of Object.values(schema.properties)) {
  assert.ok(definition.type === 'string' || Object.hasOwn(definition, 'const'));
  for (const key of Object.keys(definition)) assert.ok(['type', 'const', 'minLength', 'maxLength', 'pattern'].includes(key));
}
// This generator deliberately supports only the bounded protocol's schema subset.
// Adding a new constraint requires validators in all languages before regeneration.
// A bare $ would accept a final newline in JavaScript, unlike the native check.
assert.equal(schema.properties.requestId.pattern, '^[A-Za-z0-9._:-]+(?![\\s\\S])');
assert.equal(schema.properties.requestId.type, 'string');
assert.ok(Number.isInteger(schema.properties.requestId.minLength) && schema.properties.requestId.minLength >= 1);
assert.ok(Number.isInteger(schema.properties.requestId.maxLength) && schema.properties.requestId.maxLength >= schema.properties.requestId.minLength);
const header = '// Generated by tools/cross-platform/generate-contracts.mjs. Do not edit.\n';
let rust = header + 'use serde::Deserialize;\nuse serde::de::{Error, MapAccess, Visitor};\nuse crate::CoreError;\n';
for (const [key, value] of Object.entries(constants)) {
  rust += `pub const ${snake(key).toUpperCase()}: ${key.endsWith('Version') ? 'u32' : 'usize'} = ${value};\n`;
}
rust += '#[derive(Debug)]\npub struct CanonicalRequest {\n';
for (const [name, spec] of Object.entries(schema.properties)) {
  rust += `pub ${snake(name)}: ${typeof spec.const === 'number' ? 'f64' : 'String'},\n`;
}
// Serde's derived struct decoder also accepts positional arrays. The schema
// requires an object, with exactly one occurrence of each named field.
rust += `}
impl<'de> Deserialize<'de> for CanonicalRequest {
fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
struct RequestVisitor;
impl<'de> Visitor<'de> for RequestVisitor {
type Value = CanonicalRequest;
fn expecting(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
formatter.write_str("a canonical request object")
}
fn visit_map<A: MapAccess<'de>>(self, mut map: A) -> Result<Self::Value, A::Error> {
`;
for (const name of keys) rust += `let mut ${snake(name)} = None;\n`;
rust += 'while let Some(key) = map.next_key::<String>()? { match key.as_str() {\n';
for (const name of keys) rust += `${JSON.stringify(name)} => {
if ${snake(name)}.is_some() { return Err(A::Error::duplicate_field(${JSON.stringify(name)})); }
${snake(name)} = Some(map.next_value()?);
},\n`;
rust += `_ => return Err(A::Error::unknown_field(&key, &${JSON.stringify(keys)})),\n}}\nOk(CanonicalRequest {\n`;
for (const name of keys) rust += `${snake(name)}: ${snake(name)}.ok_or_else(|| A::Error::missing_field(${JSON.stringify(name)}))?,\n`;
rust += '})\n}\n}\ndeserializer.deserialize_map(RequestVisitor)\n}\n}\n';
rust += 'impl CanonicalRequest { pub fn validate(&self) -> Result<(), CoreError> {\n';
rust += `if self.protocol_version != ${constants.protocolVersion}.0 { return Err(CoreError { code: "unsupported_protocol", message: "Core protocol version is not supported." }); }\n`;
rust += `if self.operation != ${JSON.stringify(schema.properties.operation.const)} || ${schema.properties.requestId.minLength === 1 ? "self.request_id.is_empty()" : `self.request_id.len() < ${schema.properties.requestId.minLength}`} || self.request_id.len() > ${schema.properties.requestId.maxLength} || !self.request_id.bytes().all(|c| c.is_ascii_alphanumeric() || b"._:-".contains(&c)) { return Err(CoreError { code: "invalid_request", message: "Request does not match the core protocol." }); }\nOk(())\n} }\n`;
const formatted = spawnSync('rustfmt', ['+1.94.1', '--edition', '2024'], { input: rust, encoding: 'utf8' });
if (formatted.status !== 0) throw new Error(formatted.stderr);
rust = formatted.stdout;

let ts = header;
for (const [key, value] of Object.entries(constants)) ts += `export const ${snake(key).toUpperCase()} = ${value};\n`;
ts += 'export interface CanonicalRequest {\n';
for (const [name, spec] of Object.entries(schema.properties)) ts += `  readonly ${name}: ${Object.hasOwn(spec, 'const') ? JSON.stringify(spec.const) : 'string'};\n`;
ts += '}\nexport function isCanonicalRequest(value: unknown): value is CanonicalRequest {\n';
ts += `  if (!value || typeof value !== 'object' || Array.isArray(value)) return false;\n  const v = value as Record<string, unknown>;\n  return Object.keys(v).length === ${keys.length} && Object.keys(v).every(key => ${JSON.stringify(keys)}.includes(key))\n`;
for (const [name, spec] of Object.entries(schema.properties)) {
  ts += `    && ${Object.hasOwn(spec, 'const') ? `v.${name} === ${JSON.stringify(spec.const)}` : `typeof v.${name} === 'string'`}`;
  if (spec.minLength) ts += ` && v.${name}.length >= ${spec.minLength}`;
  if (spec.maxLength) ts += ` && v.${name}.length <= ${spec.maxLength}`;
  if (spec.pattern) ts += ` && /${spec.pattern}/.test(v.${name})`;
  ts += '\n';
}
ts += '    ;\n}\n';

let kotlin = header + 'package dev.orcaxr.core\n\n';
kotlin += 'object CoreProtocol {\n';
for (const [key, value] of Object.entries(constants)) kotlin += `    const val ${snake(key).toUpperCase()}: Int = ${value}\n`;
kotlin += '}\n\ndata class CanonicalRequest(\n';
for (const [name, spec] of Object.entries(schema.properties)) kotlin += `    val ${name}: ${typeof spec.const === 'number' ? 'Int' : 'String'},\n`;
kotlin += ') {\n    fun validate() {\n';
kotlin += `        require(protocolVersion == CoreProtocol.PROTOCOL_VERSION) { "Unsupported core protocol" }\n        require(operation == ${JSON.stringify(schema.properties.operation.const)})\n        require(requestId.length in ${schema.properties.requestId.minLength}..${schema.properties.requestId.maxLength} && Regex(${JSON.stringify(schema.properties.requestId.pattern)}).matches(requestId))\n    }\n}\n`;

const outputs = new Map([
  ['core/crates/orcaxr-contracts/src/generated.rs', rust],
  ['contracts/generated/core.ts', ts],
  ['android/core-bridge/src/main/java/dev/orcaxr/core/CoreProtocol.kt', kotlin],
]);
for (const [path, content] of outputs) {
  const target = resolve(root, path);
  if (write) { mkdirSync(dirname(target), { recursive: true }); writeFileSync(target, content); }
  else assert.equal(readFileSync(target, 'utf8'), content, `${path} needs regeneration`);
}
console.log(`${write ? 'Generated' : 'Verified'} ${outputs.size} core protocol bindings`);
