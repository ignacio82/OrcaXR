const definitions = schema.definitions;
const known = new Set();
for (const [name, shape] of Object.entries(definitions)) {
  assert.match(name, /^[A-Z][A-Za-z]+$/);
  if (
    shape.kind === "number" ||
    shape.kind === "integer" ||
    shape.kind === "wholeNumber" ||
    shape.kind === "array"
  ) {
    exact(
      shape,
      shape.kind === "array"
        ? ["kind", "items", "min", "max"]
        : ["kind", "min", "max"],
    );
    assert.ok(
      (shape.kind === "number" ? Number.isFinite(shape.min) : shape.kind === "wholeNumber"
        ? Number.isInteger(shape.min)
        : Number.isSafeInteger(shape.min)) &&
        (shape.kind === "number" || shape.min >= 0) &&
        (shape.kind === "number" ? Number.isFinite(shape.max) : shape.kind === "wholeNumber"
          ? Number.isInteger(shape.max)
          : Number.isSafeInteger(shape.max)) &&
        shape.max >= shape.min,
    );
    if (shape.kind === "array") {
      assert.ok(known.has(shape.items));
      assert.ok(shape.max <= schema.maxNodes);
    }
  } else if (shape.kind === "object" || shape.kind === "union") {
    const key = shape.kind === "object" ? "fields" : "variants";
    exact(shape, ["kind", key]);
    if (shape.kind === "union") assert.ok(Object.keys(shape[key]).length > 0);
    for (const [field, type] of Object.entries(shape[key])) {
      assert.match(field, /^[a-z][A-Za-z0-9]*$/);
      assert.ok(!["constructor", "prototype", "__proto__"].includes(field));
      assert.ok(known.has(type));
    }
  } else if (shape.kind === "enum") {
    exact(shape, ["kind", "values"]);
    assert.ok(
      Array.isArray(shape.values) &&
        shape.values.length > 0 &&
        new Set(shape.values).size === shape.values.length,
    );
    for (const value of shape.values)
      assert.match(value, /^[a-z][a-zA-Z0-9]*$/);
  } else {
    assert.equal(shape.kind, "boolean");
    exact(shape, ["kind"]);
  }
  known.add(name);
}
for (const name of schema.roots) assert.ok(known.has(name));
