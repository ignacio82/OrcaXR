const header =
  "// Generated by tools/cross-platform/generate-project-intents.mjs. Do not edit.\n";
const snake = (value) =>
  value.replace(/[A-Z]/g, (c) => "_" + c.toLowerCase()).replace(/^_/, "");
const floating = (value) =>
  /[.e]/i.test(String(value)) ? String(value) : `${value}.0`;
const title = (value) => value[0].toUpperCase() + value.slice(1);
const constants = {
  VERSION: schema.version,
  SESSION_VERSION: schema.sessionVersion,
  MAX_BYTES: schema.maxBytes,
  MAX_NODES: schema.maxNodes,
  MAX_DEPTH: schema.maxDepth,
};
let ts =
  header +
  "import { captureIntent, parseIntentJson, type IntentShape } from '../runtime/project-intents';\n";
for (const [key, value] of Object.entries(constants))
  ts += `export const PROJECT_INTENT_${key} = ${value};\n`;
ts += `const limits = ${JSON.stringify({ maxBytes: schema.maxBytes, maxNodes: schema.maxNodes, maxDepth: schema.maxDepth })};\n`;
ts += `const shapes = ${JSON.stringify(definitions, null, 2)} as const satisfies Readonly<Record<string,IntentShape>>;\n`;
let rust =
  header +
  "use serde::Serialize;\nuse serde_json::Value;\nuse super::project_intents::{InvalidIntent, fields, integer, whole_number, number, list};\n";
let kt =
  header +
  "package dev.orcaxr.core\n\nobject ProjectIntents {\n";
for (const [key, value] of Object.entries(constants)) {
  rust += `pub const ${key}: usize = ${value};\n`;
  kt += `    const val ${key} = ${value}\n`;
}
const ktType = (name, qualified = false) => {
  const s = definitions[name];
  if (s.kind === "wholeNumber" || s.kind === "number") return "Double";
  return s.kind === "integer"
    ? s.max <= 65535
      ? "Int"
      : "Long"
    : s.kind === "boolean"
      ? "Boolean"
      : s.kind === "array"
        ? `List<${ktType(s.items, qualified)}>`
        : qualified
          ? `ProjectIntents.${name}`
          : name;
};
const ktString = (value) => JSON.stringify(value).replaceAll("$", "\\$");
for (const [name, shape] of Object.entries(definitions)) {
  const type = `Project${name}Wire`;
  if (
    shape.kind === "number" ||
    shape.kind === "integer" ||
    shape.kind === "wholeNumber" ||
    shape.kind === "boolean" ||
    shape.kind === "array"
  ) {
    ts += `export type ${type} = ${["integer", "wholeNumber", "number"].includes(shape.kind) ? "number" : shape.kind === "boolean" ? "boolean" : `readonly Project${shape.items}Wire[]`};\n`;
    rust += `pub type ${name} = ${["wholeNumber", "number"].includes(shape.kind) ? "f64" : shape.kind === "integer" ? (shape.max <= 65535 ? "u16" : "u64") : shape.kind === "boolean" ? "bool" : `Vec<${shape.items}>`};\n`;
  } else if (shape.kind === "object") {
    ts += `export interface ${type} {${Object.entries(shape.fields)
      .map(([key, type]) => `readonly ${key}: Project${type}Wire;`)
      .join("")}}\n`;
    rust += `#[derive(Debug, Clone, PartialEq, Serialize)]\n#[serde(rename_all="camelCase")]\npub struct ${name} {${Object.entries(
      shape.fields,
    )
      .map(([key, type]) => `pub ${snake(key)}: ${type},`)
      .join("")}}\n`;
    kt +=
      Object.keys(shape.fields).length === 0
        ? `    data object ${name}\n`
        : `    data class ${name}(${Object.entries(shape.fields)
            .map(([key, type]) => `val ${key}: ${ktType(type)}`)
            .join(", ")})\n`;
  } else if (shape.kind === "enum") {
    ts += `export type ${type} = ${shape.values.map((v) => JSON.stringify(v)).join(" | ")};\n`;
    rust += `#[derive(Debug, Clone, PartialEq, Serialize)]\n#[serde(rename_all="camelCase")]\npub enum ${name} {${shape.values.map(title).join(",")}}\n`;
    kt += `    enum class ${name} {${shape.values.map(title).join(",")}}\n`;
  } else {
    ts += `export type ${type} = ${Object.entries(shape.variants)
      .map(([key, type]) => `{readonly ${key}:Project${type}Wire}`)
      .join(" | ")};\n`;
    rust += `#[derive(Debug, Clone, PartialEq, Serialize)]\n#[serde(rename_all="camelCase")]\npub enum ${name} {${Object.entries(
      shape.variants,
    )
      .map(([key, type]) => `${title(key)}(${type}),`)
      .join("")}}\n`;
    kt += `    sealed interface ${name} {\n${Object.entries(shape.variants)
      .map(
        ([key, type]) =>
          `        data class ${title(key)}(val value: ${ktType(type, true)}) : ${name}`,
      )
      .join("\n")}\n    }\n`;
  }
  rust += `fn read_${snake(name)}(v:&Value)->Result<${name},InvalidIntent> {\n`;
  kt += `    private fun read${name}(v: Any): ${ktType(name)} {\n`;
  if (shape.kind === "number") {
    rust += `number(v,${floating(shape.min)},${floating(shape.max)})\n`;
    kt += `        return ProjectIntentJson.number(v, ${floating(shape.min)}, ${floating(shape.max)})\n`;
  } else if (shape.kind === "wholeNumber") {
    rust += `whole_number(v,${floating(shape.min)},${floating(shape.max)})\n`;
    kt += `        return ProjectIntentJson.wholeNumber(v, ${floating(shape.min)}, ${floating(shape.max)})\n`;
  } else if (shape.kind === "integer") {
    rust += `Ok(integer(v,${shape.min},${shape.max})? as ${name})\n`;
    kt += `        return ProjectIntentJson.integer(v, ${shape.min}L, ${shape.max}L)${shape.max <= 65535 ? ".toInt()" : ""}\n`;
  } else if (shape.kind === "enum") {
    rust += `match v.as_str() {${shape.values.map((v) => `Some(${JSON.stringify(v)})=>Ok(${name}::${title(v)}),`).join("")}_=>Err(InvalidIntent)}\n`;
    kt += `        return when(v) {${shape.values.map((v) => `${ktString(v)} -> ${name}.${title(v)};`).join("")} else -> throw InvalidProjectIntent()}\n`;
  } else if (shape.kind === "boolean") {
    rust += "v.as_bool().ok_or(InvalidIntent)\n";
    kt += "        return v as? Boolean ?: throw InvalidProjectIntent()\n";
  } else if (shape.kind === "array") {
    rust += `list(v,${shape.min},${shape.max})?.iter().map(read_${snake(shape.items)}).collect()\n`;
    kt += `        val array = ProjectIntentJson.list(v, ${shape.min}, ${shape.max})\n        return List(array.length()) { read${shape.items}(array.get(it)) }\n`;
  } else {
    const entries = Object.entries(
      shape.kind === "object" ? shape.fields : shape.variants,
    );
    rust += `let ${entries.length ? "object" : "_object"}=fields(v,&${JSON.stringify(entries.map(([key]) => key))},${shape.kind === "union"})?;\n`;
    kt += `        val obj = ProjectIntentJson.fields(v, setOf(${entries.map(([key]) => ktString(key)).join(", ")}), ${shape.kind === "union"})\n`;
    if (shape.kind === "object") {
      rust += `Ok(${name}{${entries.map(([key, type]) => `${snake(key)}:read_${snake(type)}(&object[${JSON.stringify(key)}])?,`).join("")}})\n`;
      kt += `        return ${name}${entries.length ? `(${entries.map(([key, type]) => `read${type}(obj.get(${ktString(key)}))`).join(", ")})` : ""}\n`;
    } else {
      rust += `let (key,value)=object.iter().next().ok_or(InvalidIntent)?;\nmatch key.as_str() {${entries.map(([key, type]) => `${JSON.stringify(key)}=>Ok(${name}::${title(key)}(read_${snake(type)}(value)?)),`).join("")}_=>Err(InvalidIntent)}\n`;
      kt += `        return when(val key = obj.keys().next()) {\n${entries.map(([key, type]) => `            ${ktString(key)} -> ${name}.${title(key)}(read${type}(obj.get(key)))`).join("\n")}\n            else -> throw InvalidProjectIntent()\n        }\n`;
    }
  }
  rust += "}\n";
  kt += "    }\n";
  kt += `    private fun write${name}(w: ProjectIntentWriter, v: ${ktType(name)}) {\n`;
  if (shape.kind === "number")
    kt += `        w.number(v, ${floating(shape.min)}, ${floating(shape.max)})\n`;
  else if (shape.kind === "wholeNumber")
    kt += `        w.wholeNumber(v, ${floating(shape.min)}, ${floating(shape.max)})\n`;
  else if (shape.kind === "integer")
    kt += `        w.integer(v.toLong(), ${shape.min}L, ${shape.max}L)\n`;
  else if (shape.kind === "enum")
    kt += `        w.literal(when(v) {${shape.values.map((v) => `${name}.${title(v)} -> ${ktString(v)};`).join("")}})\n`;
  else if (shape.kind === "boolean") kt += "        w.boolean(v)\n";
  else if (shape.kind === "array")
    kt += `        w.array(v, ${shape.min}, ${shape.max}) { write${shape.items}(w, it) }\n`;
  else if (shape.kind === "object")
    kt += `        w.obj {\n${Object.entries(shape.fields)
      .map(
        ([key, type]) =>
          `            w.field(${ktString(key)}) { write${type}(w, v.${key}) }`,
      )
      .join("\n")}\n        }\n`;
  else
    kt += `        w.obj { when(v) {\n${Object.entries(shape.variants)
      .map(
        ([key, type]) =>
          `            is ${name}.${title(key)} -> w.field(${ktString(key)}) { write${type}(w, v.value) }`,
      )
      .join("\n")}\n        } }\n`;
  kt += "    }\n";
}
for (const name of schema.roots) {
  ts += `export function captureProject${name}(value:unknown):Project${name}Wire { return captureIntent(${JSON.stringify(name)},value,shapes,limits) as Project${name}Wire; }\n`;
  ts += `export function decodeProject${name}(text:string):Project${name}Wire { return captureProject${name}(parseIntentJson(text,limits)); }\n`;
  ts += `export function encodeProject${name}(value:Project${name}Wire):string { return JSON.stringify(captureProject${name}(value)); }\n`;
  rust += `pub fn decode_${snake(name)}(text:&str)->Result<${name},InvalidIntent> {read_${snake(name)}(&super::project_intents::parse(text)?)}\n`;
  rust += `pub fn encode_${snake(name)}(value:&${name})->Result<String,InvalidIntent> {let text=super::project_intents::encode(value)?; decode_${snake(name)}(&text)?; Ok(text)}\n`;
  kt += `    fun decode${name}(text: String): ${name} = read${name}(ProjectIntentJson.parse(text))\n`;
  kt += `    fun encode${name}(value: ${name}): String = ProjectIntentWriter().also { write${name}(it, value) }.finish()\n`;
}
kt += "}\n";
// Every helper must be used. Unreachable definitions indicate schema drift.
for (const name of Object.keys(definitions)) {
  if (!schema.roots.includes(name))
    assert.ok(
      Object.values(definitions).some(
        (s) =>
          s.items === name ||
          Object.values(s.fields ?? s.variants ?? {}).includes(name),
      ),
      `Unreachable ${name}`,
    );
}
// File input avoids bounded subprocess-pipe capacity for a growing schema.
const formatDirectory = mkdtempSync(join(tmpdir(), "orcaxr-project-intents-"));
let formattedRust;
try {
  const path = join(formatDirectory, "bindings.rs");
  writeFileSync(path, rust);
  const formatted = spawnSync("rustfmt", ["+1.94.1", "--edition", "2024", path], {
    stdio: "inherit", timeout: 30000,
  });
  assert.equal(formatted.status, 0, formatted.error?.message);
  formattedRust = readFileSync(path, "utf8");
} finally {
  rmSync(formatDirectory, { recursive: true, force: true });
}
for (const [path, content] of [
  ["contracts/generated/project-intents.ts", ts],
  [
    "core/crates/orcaxr-contracts/src/project_intent_types.rs",
    formattedRust,
  ],
  ["android/core-bridge/src/main/java/dev/orcaxr/core/ProjectIntents.kt", kt],
]) {
  const target = new URL(path, root);
  if (process.argv.includes("--write")) writeFileSync(target, content);
  else
    assert.equal(
      readFileSync(target, "utf8"),
      content,
      `${path} needs regeneration`,
    );
}
