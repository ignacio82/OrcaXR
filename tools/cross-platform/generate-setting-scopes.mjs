// Reuse the pinned engine extractor; never reconstruct native scope defaults.
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import {
  buildScopeTable,
  renderScopeModule,
  OUTPUT_PATH,
} from "../settings-schema/generate-scopes.mjs";

const table = buildScopeTable();
assert.equal(
  readFileSync(OUTPUT_PATH, "utf8"),
  renderScopeModule(table),
  "Browser scope table drift",
);
const variants = {
  project: "Project",
  plate: "Plate",
  object: "Object",
  part: "Part",
  layerRange: "LayerRange",
};
assert.deepEqual(table.order, Object.keys(variants));
const digest = createHash("sha256").update(JSON.stringify(table)).digest("hex");
let rust =
  "// Generated by tools/cross-platform/generate-setting-scopes.mjs. Do not edit.\nuse super::SettingScope;\n";
rust += `pub const SOURCE_COMMIT: &str = ${JSON.stringify(table.source.commit)};\n`;
rust += `pub const SOURCE_DIGEST: &str = ${JSON.stringify(digest)};\n`;
rust += `pub const SOURCE_FILES: &[(&str, &str)] = &[${table.source.files.map((file) => `(${JSON.stringify(file.path)},${JSON.stringify(file.blob)})`).join(",")}];\n`;
rust += `pub const SCOPE_ORDER: &[SettingScope] = &[${table.order.map((scope) => `SettingScope::${variants[scope]}`).join(",")}];\n`;
rust +=
  "pub fn keys(scope: SettingScope) -> &'static [&'static str] { match scope {\n";
for (const scope of table.order) {
  const keys = table.scopes[scope];
  assert.deepEqual(keys, [...new Set(keys)].sort());
  for (const key of keys) assert.match(key, /^[a-z0-9_]+$/);
  rust += `SettingScope::${variants[scope]} => &[${keys.map(JSON.stringify).join(",")}],\n`;
}
rust += "}}\n";
const formatted = spawnSync("rustfmt", ["+1.94.1", "--edition", "2024"], {
  input: rust,
  encoding: "utf8",
});
assert.equal(formatted.status, 0, formatted.stderr);
const output = new URL(
  "../../core/crates/orcaxr-project/src/settings/generated.rs",
  import.meta.url,
);
if (process.argv.includes("--write")) writeFileSync(output, formatted.stdout);
else
  assert.equal(
    readFileSync(output, "utf8"),
    formatted.stdout,
    "Native scope table drift",
  );
console.log(
  `Native settings scopes: ${digest}, ${table.order.map((scope) => `${scope}=${table.scopes[scope].length}`).join(", ")}`,
);
