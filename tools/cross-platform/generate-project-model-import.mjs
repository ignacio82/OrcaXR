// Host model-import limits: the browser's `ModelImportLimits`, with its exact
// defaults (asserted against web/src/project/import/formats/types.ts). Generates
// the Rust decoder, TypeScript and Kotlin encoders.
import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
const root = new URL("../../", import.meta.url);
const s = JSON.parse(readFileSync(new URL("contracts/project-model-import.json", root)));
assert.deepEqual(Object.keys(s).sort(), ["defaults", "maxBudget", "maxChunkBytes", "options", "version"]);
assert.equal(s.maxBudget, 0xffffffff);
assert.equal(s.options.length, s.defaults.length);
const browser = readFileSync(new URL("web/src/project/import/formats/types.ts", root), "utf8");
const block = /DEFAULT_MODEL_IMPORT_LIMITS: ModelImportLimits = Object\.freeze\(\{([^}]*)\}\)/.exec(browser)?.[1];
assert.ok(block, "browser default limits");
const browserDefaults = Object.fromEntries(
  [...block.matchAll(/(\w+):\s*([\d_ *]+),/g)].map(([, key, value]) => [key, Function(`return ${value.replaceAll("_", "")}`)()]),
);
assert.deepEqual(browserDefaults, Object.fromEntries(s.options.map((key, i) => [key, s.defaults[i]])), "defaults match the browser");
for (const value of s.defaults) assert.ok(Number.isSafeInteger(value) && value >= 1 && value <= s.maxBudget);
const snake = (name) => name.replace(/[A-Z]/g, (c) => "_" + c.toLowerCase());
const header = "// Generated by tools/cross-platform/generate-project-model-import.mjs. Do not edit.\n";
let rust = header + "use super::Limits;\n";
rust += `pub const VERSION: usize = ${s.version};\npub const MAX_CHUNK_BYTES: usize = ${s.maxChunkBytes};\npub const MAX_BUDGET: usize = ${s.maxBudget};\npub const OPTION_COUNT: usize = ${s.options.length};\n`;
rust += `/// Exact version and positive integral limits within \`MAX_BUDGET\`.
pub fn decode_options(version: f64, input: &[f64]) -> Option<Limits> {
    if version != VERSION as f64
        || input.len() != OPTION_COUNT
        || input
            .iter()
            .any(|v| !v.is_finite() || v.fract() != 0.0 || *v < 1.0 || *v > MAX_BUDGET as f64)
    {
        return None;
    }
    Some(Limits {
`;
for (const [i, key] of s.options.entries()) rust += `        ${snake(key)}: input[${i}] as usize,\n`;
rust += `    })
}
`;
let ts = header + `export const PROJECT_MODEL_IMPORT = ${JSON.stringify(s, null, 2)} as const;\nexport interface ProjectModelImportOptions {\n`;
for (const key of s.options) ts += `  readonly ${key}: number;\n`;
ts += `}
export function encodeProjectModelImportOptions(value: ProjectModelImportOptions): Float64Array {
  const keys = Reflect.ownKeys(value);
  if (keys.length !== PROJECT_MODEL_IMPORT.options.length || keys.some(k => typeof k !== 'string' || !(PROJECT_MODEL_IMPORT.options as readonly string[]).includes(k))) throw new Error('Invalid project model import options');
  return new Float64Array(PROJECT_MODEL_IMPORT.options.map(key => {
    const field = Object.getOwnPropertyDescriptor(value, key);
    const number: unknown = field?.value;
    if (!field || !('value' in field) || typeof number !== 'number' || !Number.isInteger(number) || number < 1 || number > PROJECT_MODEL_IMPORT.maxBudget) throw new Error('Invalid project model import options');
    return number;
  }));
}
`;
let kotlin = header + "package dev.orcaxr.core\n\nobject ProjectModelImport {\n";
kotlin += `    const val VERSION = ${s.version}\n    const val MAX_CHUNK_BYTES = ${s.maxChunkBytes}\n    const val MAX_BUDGET = ${s.maxBudget}L\n    const val OPTION_COUNT = ${s.options.length}\n}\n\n`;
kotlin += "/** Defaults are the browser's model import limits. */\ndata class ProjectModelImportOptions(\n";
for (const [i, key] of s.options.entries()) kotlin += `    val ${key}: Long = ${s.defaults[i]},\n`;
kotlin += `) {\n    fun encode(): DoubleArray {\n        val values = longArrayOf(${s.options.join(", ")})\n        require(values.all { it in 1..ProjectModelImport.MAX_BUDGET }) { "Invalid project model import options" }\n        return values.map { it.toDouble() }.toDoubleArray()\n    }\n}\n`;
for (const [path, content] of [
  ["core/crates/orcaxr-archive/src/models/layout.rs", rust],
  ["contracts/generated/project-model-import.ts", ts],
  ["android/core-bridge/src/main/java/dev/orcaxr/core/ProjectModelImport.kt", kotlin],
]) {
  const url = new URL(path, root);
  if (process.argv.includes("--write")) writeFileSync(url, content);
  else assert.equal(readFileSync(url, "utf8"), content, `${path} requires regeneration`);
}
console.log("Verified shared project model import limits");
