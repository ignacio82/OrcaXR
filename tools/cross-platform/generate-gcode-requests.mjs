const ktStr = (value) => JSON.stringify(value).replaceAll("$", "\\$");
function ktType(field) {
  const value =
    field.type === "array"
      ? `List<${ktType({ type: field.items })}>`
      : {
          number: "Double",
          u8: "Int",
          u16: "Int",
          u32: "Long",
          string: "String",
          boolean: "Boolean",
          text: "List<Int>",
          range: "List<Double>",
          window: "Window",
        }[field.type] || field.type;
  return value + (field.optional ? "?" : "");
}
function ktShape(field) {
  let value = field.literal
    ? `GcodeRequestShape.Literal(${ktStr(field.literal)})`
    : definitions[field.type]
      ? `${field.type}Shape`
      : `GcodeRequestShape.${title(field.type === "array" ? "array" : field.type)}`;
  if (field.type === "array") value += `(${ktShape({ type: field.items })})`;
  return value;
}
function ktWrite(field, variable) {
  if (definitions[field.type]) return `${variable}.write(w)`;
  if (field.type === "array")
    return `w.array(${variable}) { item -> ${ktWrite({ type: field.items }, "item")} }`;
  if (field.type === "text")
    return `w.array(${variable}) { item -> w.u16(item) }`;
  return `w.${field.type}(${variable})`;
}
