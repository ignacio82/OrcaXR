function expr(field, variable) {
  let value;
  if (field.literal) value = `${variable}===${JSON.stringify(field.literal)}`;
  else if (definitions[field.type]) value = `valid${field.type}(${variable},b)`;
  else {
    const node = field.type === "array" ? field : primitives[field.type];
    if (node.type === "number") {
      value = `typeof ${variable}==='number'&&Number.${node.integer ? "isSafeInteger" : "isFinite"}(${variable})`;
      if (node.integer)
        value += `&&${variable}>=${node.min}&&${variable}<=${node.max}`;
    } else if (node.type === "string")
      value = `typeof ${variable}==='string'&&${variable}.length<=GCODE_REQUEST_MAX_VIEW_BYTES`;
    else if (node.type === "boolean") value = `typeof ${variable}==='boolean'`;
    else {
      value = `array(${variable},${JSON.stringify(node.items)},b,(item,b)=>${expr({ type: node.items }, "item")})`;
      if (node.length !== undefined)
        value += `&&(${variable} as ArrayLike<unknown>).length===${node.length}`;
      if (node.lengths)
        value += `&&Array.isArray(${variable})&&(${variable}.length===0||(${variable}.length===2&&${variable}[0]<=${variable}[1]))`;
    }
  }
  if (field.nullable) value = `(${variable}===null||(${value}))`;
  return optional(field) ? `(${variable}===undefined||(${value}))` : value;
}
