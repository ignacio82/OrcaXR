function tsType(field) {
  let value;
  if (field.literal) return JSON.stringify(field.literal);
  if (field.type === "array")
    value =
      `readonly (${tsType({ type: field.items })})[]` +
      ({ u8: " | Uint8Array", u16: " | Uint16Array", u32: " | Uint32Array" }[
        field.items
      ] || "");
  else
    value =
      {
        number: "number",
        u8: "number",
        u16: "number",
        u32: "number",
        string: "string",
        boolean: "boolean",
        text: "readonly number[] | Uint16Array",
        range: "readonly [number, number]",
        window: "readonly [] | readonly [number, number]",
      }[field.type] || `Gcode${field.type}Wire`;
  return field.nullable ? `(${value}) | null` : value;
}
