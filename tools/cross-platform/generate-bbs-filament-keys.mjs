// Extract the production BBS writer's pinned per-filament vector policy.
import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import ts from "../../web/node_modules/typescript/lib/typescript.js";
const root = new URL("../../", import.meta.url),
  path = "web/src/project/serialization/bbsCore.ts";
assert.ok(process.argv.slice(2).every((v) => v === "--write"));
const source = ts.createSourceFile(
  path,
  readFileSync(new URL(path, root), "utf8"),
  ts.ScriptTarget.Latest,
  true,
);
let keys;
for (const statement of source.statements)
  if (ts.isVariableStatement(statement))
    for (const d of statement.declarationList.declarations) {
      if (ts.isIdentifier(d.name) && d.name.text === "FILAMENT_VECTOR_KEYS") {
        assert.ok(ts.isArrayLiteralExpression(d.initializer));
        keys = d.initializer.elements.map((v) => {
          assert.ok(ts.isStringLiteral(v));
          return v.text;
        });
      }
    }
assert.ok(keys?.length);
assert.equal(new Set(keys).size, keys.length);
assert.ok(keys.every((v) => /^[A-Za-z_]+$/.test(v)));
const text = `// Generated by tools/cross-platform/generate-bbs-filament-keys.mjs.\n// Policy: production bbsCore.ts FILAMENT_VECTOR_KEYS (pinned Preset.cpp whitelist).\npub(super) const KEYS: &[&str] = &[\n${keys.map((v) => `    "${v}",`).join("\n")}\n];\n`;
const out = new URL(
  "core/crates/orcaxr-archive/src/bbs/model/settings/filament_keys.rs",
  root,
);
if (process.argv.includes("--write")) writeFileSync(out, text);
else assert.equal(readFileSync(out, "utf8"), text, "Stale BBS filament keys");
console.log(`BBS filament vector policy: ${keys.length} keys`);
