import { readFileSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import assert from "node:assert/strict";
const root = new URL("../../", import.meta.url);
const schema = JSON.parse(
  readFileSync(new URL("contracts/gcode-preview.json", root)),
);
assert.deepEqual(
  Object.keys(schema).sort(),
  [
    "version",
    "modes",
    "roleNames",
    "roleRgba",
    "eventLabels",
    "eventRgba",
    "rangeColors",
    "legendPatterns",
  ].sort(),
);
assert.equal(schema.version, 1);
assert.equal(schema.modes.length, 12);
assert.equal(schema.roleNames.length, 20);
assert.equal(schema.roleRgba.length, 20);
assert.equal(schema.eventLabels.length, 14);
assert.equal(schema.eventRgba.length, 14);
assert.equal(schema.rangeColors.length, 10);
assert.equal(schema.legendPatterns.length, 6);
const str = JSON.stringify;
const color = (value) => {
  assert.ok(
    Array.isArray(value) &&
      value.length === 4 &&
      value.every((v) => Number.isFinite(v) && v >= 0 && v <= 1),
  );
  return (
    "[" +
    value.map((v) => (Number.isInteger(v) ? v + ".0" : String(v))).join(",") +
    "]"
  );
};
let rust =
  "// Generated by tools/cross-platform/generate-preview-catalog.mjs. Do not edit.\nuse super::ModeDefinition;\npub const MODES: [ModeDefinition; 12] = [\n";
for (const mode of schema.modes) {
  assert.deepEqual(
    Object.keys(mode).sort(),
    ["id", "label", "valueKind", "unit", "scale"].sort(),
  );
  assert.ok(["category", "number"].includes(mode.valueKind));
  assert.ok(["categorical", "linear", "log"].includes(mode.scale));
  rust += `ModeDefinition { id:${str(mode.id)}, label:${str(mode.label)}, value_kind:${str(mode.valueKind)}, unit:${mode.unit === null ? "None" : `Some(${str(mode.unit)})`}, scale:${str(mode.scale)}},\n`;
}
rust += "];\n";
for (const [name, key] of [
  ["ROLE_NAMES", "roleNames"],
  ["EVENT_LABELS", "eventLabels"],
  ["PATTERNS", "legendPatterns"],
])
  rust += `pub const ${name}: [&str; ${schema[key].length}] = ${str(schema[key])};\n`;
rust +=
  "pub const ROLE_RGBA: [Option<[f64;4]>;20] = [" +
  schema.roleRgba
    .map((v) => (v === null ? "None" : `Some(${color(v)})`))
    .join(",") +
  "];\n";
rust +=
  "pub const EVENT_RGBA: [[f64;4];14] = [" +
  schema.eventRgba.map(color).join(",") +
  "];\n";
rust +=
  "pub const RANGE_RGBA: [[f64;4];10] = [" +
  schema.rangeColors
    .map((value) => {
      assert.match(value, /^#[0-9A-F]{6}$/);
      return (
        "[" +
        [1, 3, 5]
          .map((n) => parseInt(value.slice(n, n + 2), 16) + ".0/255.0")
          .join(",") +
        ",1.0]"
      );
    })
    .join(",") +
  "];\n";
const formatted = spawnSync("rustfmt", ["+1.94.1", "--edition", "2024"], {
  input: rust,
  encoding: "utf8",
});
assert.equal(formatted.status, 0, formatted.stderr);
const path = new URL("core/crates/orcaxr-gcode/src/preview_catalog.rs", root);
if (process.argv.includes("--write")) writeFileSync(path, formatted.stdout);
else
  assert.equal(
    readFileSync(path, "utf8"),
    formatted.stdout,
    "Preview catalog drifted",
  );
console.log("Verified shared preview catalog");
