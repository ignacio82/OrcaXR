// Generate the schema-1 record shapes the browser checks before admitting a
// canonical state, from the native core's own model declarations
// (`core/crates/orcaxr-project/src/model/mod.rs`: `record!`, `text_enum!`,
// `number_enum!`, `bool_literal!`; `ids.rs`: `entity_kinds!`), so the two cannot drift: a field the core
// requires, the browser requires. Fails on any declaration it cannot read.
import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../../", import.meta.url);
const source = readFileSync(
  new URL("core/crates/orcaxr-project/src/model/mod.rs", root),
  "utf8",
);
const idSource = readFileSync(
  new URL("core/crates/orcaxr-project/src/ids.rs", root),
  "utf8",
);
const output = new URL("contracts/generated/project-shape.ts", root);

/** Split on commas outside `<…>` and `[…]` (a `=>` arrow is not a bracket). */
function topLevel(text) {
  const parts = [];
  let depth = 0;
  let start = 0;
  for (let i = 0; i < text.length; i += 1) {
    const c = text[i];
    if (c === "<" || c === "[") depth += 1;
    else if ((c === ">" && text[i - 1] !== "=") || c === "]") depth -= 1;
    else if (c === "," && depth === 0) {
      parts.push(text.slice(start, i));
      start = i + 1;
    }
  }
  parts.push(text.slice(start));
  return parts.map((p) => p.trim()).filter(Boolean);
}

const records = {};
for (const [, name, body] of source.matchAll(
  /^record!\((\w+) \{(.*)\}\);$/gm,
)) {
  records[name] = topLevel(body).map((field) => {
    const match = /^(\w+)=>"([^"]+)":(.+)$/.exec(field);
    assert.ok(match, `unreadable field ${field} of ${name}`);
    return [match[2], match[3].replaceAll(" ", "")];
  });
}
const textEnums = {};
for (const [, name, body] of source.matchAll(
  /^text_enum!\((\w+) \{(.*)\}\);$/gm,
)) {
  textEnums[name] = topLevel(body).map((variant) => {
    const match = /^\w+=>"([^"]*)"$/.exec(variant);
    assert.ok(match, `unreadable literal ${variant} of ${name}`);
    return match[1];
  });
}
const numberEnums = {};
for (const [, name, body] of source.matchAll(
  /^number_enum!\((\w+) \{(.*)\}\);$/gm,
)) {
  numberEnums[name] = topLevel(body).map((variant) => {
    const match = /^\w+\s*=>\s*(-?\d+)$/.exec(variant);
    assert.ok(match, `unreadable number ${variant} of ${name}`);
    return Number(match[1]);
  });
}
const kinds = /^entity_kinds! \{([^}]*)\}/m.exec(idSource);
assert.ok(kinds, "entity_kinds! is declared");
const entityIds = topLevel(kinds[1]).map((kind) => {
  const match = /^\w+\s*=>\s*(\w+)$/.exec(kind);
  assert.ok(match, `unreadable entity kind ${kind}`);
  return match[1];
});
const boolLiterals = {};
for (const [, name, value] of source.matchAll(
  /^bool_literal!\((\w+), (true|false)\);$/gm,
))
  boolLiterals[name] = value === "true";

// Every declared record line must have been read: a record! the regex missed
// would silently drop a whole shape.
assert.equal(
  Object.keys(records).length,
  (source.match(/^record!\(/gm) ?? []).length,
  "every record! read",
);
assert.equal(
  Object.keys(textEnums).length,
  (source.match(/^text_enum!\(/gm) ?? []).length,
  "every text_enum! read",
);
assert.equal(
  Object.keys(numberEnums).length,
  (source.match(/^number_enum!\(/gm) ?? []).length,
  "every number_enum! read",
);
assert.ok(records.ProjectState, "ProjectState is declared");

const text = `// Generated by tools/cross-platform/generate-project-shape.mjs from
// core/crates/orcaxr-project/src/model/mod.rs. Do not edit by hand.
/** Schema-1 records: each field's wire name and native type. */
export const PROJECT_SHAPE_RECORDS: Readonly<Record<string, readonly (readonly [string, string])[]>> = ${JSON.stringify(records, null, 2)};
/** Text literals by type. */
export const PROJECT_SHAPE_TEXT_ENUMS: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(textEnums, null, 2)};
/** Number literals by type. */
export const PROJECT_SHAPE_NUMBER_ENUMS: Readonly<Record<string, readonly number[]>> = ${JSON.stringify(numberEnums, null, 2)};
/** Types decoded as stable entity IDs. */
export const PROJECT_SHAPE_ENTITY_IDS: readonly string[] = ${JSON.stringify(entityIds)};
/** Boolean literals by type. */
export const PROJECT_SHAPE_BOOL_LITERALS: Readonly<Record<string, boolean>> = ${JSON.stringify(boolLiterals, null, 2)};
`;
if (process.argv.includes("--write")) writeFileSync(output, text);
else
  assert.equal(
    readFileSync(output, "utf8"),
    text,
    "Project shape contract drift",
  );
console.log(
  `Project shape: ${Object.keys(records).length} records, ${Object.keys(textEnums).length} text enums, ${Object.keys(numberEnums).length} number enums, ${Object.keys(boolLiterals).length} boolean literals, ${entityIds.length} entity IDs`,
);
